"""Release drill report (design §6, §16 M4) -> docs/results/release.md.

Input: artifacts/release/drill.json, written by sim.release_drill: the steps with their times
and the api's answers, the release record (model_version_events), the canary's guardrails and
the simulated traffic per phase and per 10 s.

Usage: python -m analysis.release_report
"""

from __future__ import annotations

import datetime as dt
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DRILL = ROOT / "artifacts" / "release" / "drill.json"
BUNDLES = ROOT / "artifacts" / "bundles"
OUT = ROOT / "docs" / "results" / "release.md"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    return ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + [
        "| " + " | ".join(r) + " |" for r in rows
    ]


def _utc(t: float) -> str:
    return dt.datetime.fromtimestamp(t, dt.UTC).strftime("%H:%M:%S")


def _pct(x) -> str:
    return "n/a" if x is None or x != x else f"{x:.2%}"


def _ms(x) -> str:
    return "n/a" if x is None or x != x else f"{x:.1f}"


_PATH = re.compile(r"(?<![\w.])/(?:[\w.@+-]+/)+([\w.@+-]+)")


def _scrub(text: str) -> str:
    """A local absolute path in a note shows as its last component (the report is published)."""
    return _PATH.sub(r"\1", text)


def _reasons(r: dict | None) -> str:
    return ", ".join(f"{k} {n:,}" for k, n in (r or {}).items()) or "none"


def _s(x) -> str:
    return "none" if x is None else str(x)


def _valid_ndcg(version: str) -> float | None:
    m = BUNDLES / version / "manifest.json"
    if not m.exists():
        return None
    valid = json.loads(m.read_text())["models"]["sasrec"].get("valid") or {}
    return valid.get("NDCG@10")


def _bundle(version: str) -> str:
    m = BUNDLES / version / "manifest.json"
    if not m.exists():
        return ""
    man = json.loads(m.read_text())
    sas = man["models"]["sasrec"]["config"]
    parts = [
        f"SASRec {sas['loss'].upper()} loss, best epoch {man['models']['sasrec']['best_epoch']}"
    ]
    r = man.get("ranking", {}).get("ranker")
    if r:
        parts.append(f"LightGBM ranker ({r['rounds']} trees)")
    pc = man.get("pctr")
    parts.append(f"pCTR {pc['model']} (trained on {', '.join(pc['days'])})" if pc else "fixed pCTR")
    valid = man["models"]["sasrec"].get("valid") or {}
    if valid:
        parts.append(f"SASRec validation NDCG@10 {valid['NDCG@10']:.4f}")
    test = man["models"]["sasrec"].get("test") or {}
    if test:
        parts.append(f"SASRec test HR@10 {test['HR@10']:.4f}")
    return "; ".join(parts)


def arm_rows(summary: dict) -> list[list[str]]:
    return [
        [
            a,
            f"{v['page_views']:,}",
            f"{v['users']:,}",
            _pct(v["degraded_share"]),
            _ms(v["p50_ms"]),
            _ms(v["p99_ms"]),
            f"{v['impressions']:,}",
            f"{v['clicks']:,}",
            _pct(v["ctr"]),
        ]
        for a, v in summary["arms"].items()
    ]


def _pause(args: dict) -> str:
    if "think_ms" not in args:
        return ""
    lo, hi = args["think_ms"]
    return f" pausing {lo:.0f}-{hi:.0f} ms between page views"


def _redis_line(r: dict | None) -> list[str]:
    """What the drill did to the two Redis instances (sim/redis_stats.py)."""
    if not r:
        return []
    st, ca = r["state"], r["cache"]
    ok = st["evicted_keys"] == 0 and st["oom_errors"] == 0
    return [
        "",
        f"Redis during the drill: the state instance ({st['policy']}, {st['maxmemory_mb']} MB) evicted "
        f"{st['evicted_keys']:,} keys and refused {st['oom_errors']:,} writes"
        + ("" if ok else " (**the drill's user state is not complete**)")
        + f"; the cache instance ({ca['policy']}, {ca['maxmemory_mb']} MB) evicted {ca['evicted_keys']:,}.",
    ]


def render(d: dict) -> str:
    t0 = d["t0"]
    steps = d["steps"]
    lines = [
        "# Release drill: canary, full rollout, rollback",
        "",
        "<!-- Generated by `make release-report` (analysis/release_report.py). Do not edit by hand. -->",
        "",
        "One run of `make release-drill` (`sim/release_drill.py`) against the api and the model server, with simulated "
        f"traffic ({d['args']['concurrency']} concurrent sessions{_pause(d['args'])}, the standing campaigns in the "
        "sponsored slots) running "
        "throughout. Every step went through the api's admin endpoints, the ones the admin page's buttons call; the "
        "release state lives in PostgreSQL (`model_versions`), and every transition is a row of `model_version_events` "
        "(below).",
        *_redis_line(d.get("redis")),
        "",
        *_table(
            ["Role", "Version", "What is in it"],
            [
                ["active before the drill", f"`{d['old']}`", _bundle(d["old"])],
                ["the release", f"`{d['new']}`", _bundle(d["new"])],
                ["the bad release", f"`{d['bad']}`", _bundle(d["bad"])],
            ],
        ),
        "",
        "## Steps",
        "",
        *_table(
            ["t (s)", "UTC", "Step", "Took (s)", "Result"],
            [
                [
                    f"{s['t'] - t0:.0f}",
                    _utc(s["t"]),
                    s["step"],
                    f"{s['seconds']:.2f}",
                    "ok" if s["ok"] else "**failed**",
                ]
                for s in steps
            ],
        ),
        "",
    ]
    c = d.get("canary")
    if c:
        diff = c["ctr_diff"]
        lines += [
            f"## Canary ({d['args']['canary_percent']}% of users, {(c['to'] - c['from']) / 60:.0f} min)",
            "",
            "The release-canary experiment pins the users of rank-layer buckets [0, "
            f"{d['args']['canary_percent'] * 10}) to the new version (`pin_version`); everyone else stays on the active one. "
            "Both arms over the same minutes:",
            "",
            *_table(
                [
                    "Arm",
                    "Page views",
                    "Users",
                    "Degraded",
                    "Client P50 (ms)",
                    "Client P99 (ms)",
                    "Impressions",
                    "Clicks",
                    "CTR",
                ],
                arm_rows(c["summary"]),
            ),
            "",
            f"Failed page views in the window: {c['summary']['failed_page_views']}. CTR canary - rest: {diff[0]:+.4f}, "
            f"95% CI [{diff[1]:+.4f}, {diff[2]:+.4f}] (user-level bootstrap).",
            "",
            *_table(
                ["Guardrail", "Rule", "Result"],
                [
                    [
                        "Failed page views",
                        "none",
                        "pass" if c["checks"]["failed_page_views"] else "**fail**",
                    ],
                    [
                        "Degraded share",
                        "canary at most 1 point above the rest",
                        "pass" if c["checks"]["degraded"] else "**fail**",
                    ],
                    ["Client P99", "under 100 ms", "pass" if c["checks"]["p99"] else "**fail**"],
                    [
                        "CTR",
                        "not significantly lower (upper end of the CI above 0)",
                        "pass" if c["checks"]["ctr_not_lower"] else "**fail**",
                    ],
                ],
            ),
            "",
            f"Decision: {'full rollout' if c['pass'] else 'abort the canary'}.",
            "",
        ]
    sw = d.get("switch", {})
    lines += ["## Switches", ""]
    lines += _table(
        [
            "Switch",
            "First page on the new version after (s)",
            "Last first page on another version after (s)",
        ],
        [
            [
                label,
                _s(sw.get(k, {}).get("first_page_s")),
                _s(sw.get(k, {}).get("last_other_page_s")),
            ]
            for k, label in (
                ("full", "full rollout"),
                ("bad", "bad release"),
                ("rollback", "rollback"),
            )
        ],
    )
    lines += [
        "",
        "A request reads the active version once and uses it for every stage, so the pages in flight at a switch finish on "
        "the version they started with; the next ones get the new version. A next page keeps the version of the list it "
        "pages through (not counted above).",
        "",
        "## Phases",
        "",
    ]
    rows = []
    for name, ph in d["phases"].items():
        for arm, v in ph["arms"].items():
            rows.append(
                [
                    name,
                    f"`{arm}`",
                    f"{v['page_views']:,}",
                    _pct(v["degraded_share"]),
                    _reasons(v.get("degraded_reasons")),
                    _ms(v["p99_ms"]),
                    _pct(v["ctr"]),
                    str(ph["failed_page_views"]),
                ]
            )
    lines += _table(
        [
            "Phase",
            "Version",
            "Page views",
            "Degraded",
            "Most frequent reasons",
            "Client P99 (ms)",
            "CTR",
            "Failed page views (phase)",
        ],
        rows,
    )
    lines += [
        "",
        "A phase runs from the step that started it to the next one, by the steps' own times"
        + (
            "; a version that served a handful of pages at the start of a phase is the in-flight requests of the switch"
            if any(len(ph["arms"]) > 1 and name != "canary" for name, ph in d["phases"].items())
            else ""
        )
        + ". Degradation reasons are "
        "the api's (`<dependency>_timeout`: a call over its stage's budget, the request served without it; "
        "`pctr_error`: no pCTR, so no ads on that page)."
        + (
            f" These tables were re-derived from the drill's ledger and steps afterwards (`{d['analysed']['by']}`)."
            if d.get("analysed")
            else ""
        ),
    ]
    fails = d.get("failures") or []
    if fails:
        lines += ["", "Failed page views:", ""]
        lines += _table(
            ["t (s)", "Surface", "Status", "Client ms", "Degradations within 5 s"],
            [
                [
                    f"{f['t'] - t0:.1f}",
                    str(f["surface"]),
                    str(f["status"]),
                    _ms(f["ms"]),
                    _reasons(f["degraded_around"]),
                ]
                for f in fails
            ],
        )
    bad = d.get("bad_vs_full_ctr")
    if bad:
        lower = bad[2] < 0
        lines += [
            "",
            f"The bad release against the full rollout before it, CTR: {bad[0]:+.4f}, 95% CI [{bad[1]:+.4f}, "
            f"{bad[2]:+.4f}] (user-level bootstrap over the two phases' users); "
            + ("lower." if lower else "the interval includes 0.")
            + " Consecutive phases are not a fair comparison of versions, though: they differ in time too, and CTR "
            "falls with every home page a user has already seen in the drill, whatever the version (table below: the "
            "items seen in the last 24 hours are filtered out, so the same users' later pages show weaker matches). A "
            "version comparison needs the same minutes, which is what the canary's split gives.",
        ]
        nb, nn = _valid_ndcg(d["bad"]), _valid_ndcg(d["new"])
        quality = (
            f" Offline, its SASRec reaches validation NDCG@10 {nb:.4f} against {nn:.4f}: that is what tells the two "
            "versions apart."
            if nb is not None and nn is not None
            else ""
        )
        lines += [
            "",
            "What the drill shows is the mechanism: the bad release passed validation (its files are consistent and its "
            "golden queries reproduce; validation does not judge quality), went out without a canary, and the rollback "
            "returned to the previous version, still loaded, in one switch." + quality,
        ]
    pc = d.get("ctr_by_page_count")
    if pc:
        lines += [
            "",
            "CTR by how many home pages the user had seen in the drill, all versions:",
            "",
        ]
        lines += _table(
            ["User's home page", "Impressions", "Clicks", "CTR"],
            [
                [
                    f"{r['pages'][0]}-{r['pages'][1]}"
                    if r["pages"][1]
                    else f"{r['pages'][0]} and later",
                    f"{r['impressions']:,}",
                    f"{r['clicks']:,}",
                    _pct(r["ctr"]),
                ]
                for r in pc
            ],
        )
    lines += ["", "## Release record (`model_version_events`)", ""]
    lines += _table(
        ["UTC", "Version", "From", "To", "Actor", "Note"],
        [
            [
                _utc(e["at"]),
                f"`{e['version']}`",
                e["from"] or "",
                e["to"],
                e["actor"],
                _scrub(e["note"] or "").replace("|", "\\|"),
            ]
            for e in d["events"]
        ],
    )
    lines += ["", "## Traffic per 10 s around the switches", ""]
    marks = [
        s["t"] - t0 for s in steps if s["step"].startswith(("full rollout", "activate", "rollback"))
    ]
    rows = []
    for r in d["timeline"]:
        if any(m - 20 <= r["t"] <= m + 30 for m in marks):
            vs = ", ".join(f"{v[:24]}: {n}" for v, n in sorted(r["versions"].items()))
            rows.append([f"{r['t']:.0f}", vs, str(r["failed"]), _ms(r["p99_ms"])])
    lines += _table(["t (s)", "First and next pages by version", "Failed", "Client P99 (ms)"], rows)
    lines += [""]
    return "\n".join(lines)


def main() -> None:
    if not DRILL.exists():
        raise SystemExit(f"{DRILL} is missing: run `make release-drill`")
    d = json.loads(DRILL.read_text())
    OUT.write_text(render(d))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
