-- Ads and billing (docs/design.md §9, §12.1): advertisers and their campaigns (managed through
-- the api), one budget row per campaign and UTC day, the charge ledger and the log of every
-- sponsored click billing processed. Money is in integer cents.

-- +goose Up
CREATE TABLE advertisers (
  advertiser_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL CHECK (name <> ''),
  brand         TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE campaigns (
  campaign_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  advertiser_id      INT NOT NULL REFERENCES advertisers,
  name               TEXT NOT NULL CHECK (name <> ''),
  -- 'ended' is terminal: the row stays because the ledger refers to it.
  status             TEXT NOT NULL CHECK (status IN ('active', 'paused', 'ended')),
  daily_budget_cents INT NOT NULL CHECK (daily_budget_cents > 0),
  bid_cpc_cents      INT NOT NULL CHECK (bid_cpc_cents > 0),
  freq_cap_per_day   INT NOT NULL DEFAULT 3 CHECK (freq_cap_per_day > 0),
  start_at           TIMESTAMPTZ,
  end_at             TIMESTAMPTZ,
  targeting          JSONB,                  -- e.g. {"categories": [...]}
  version            INT NOT NULL DEFAULT 1, -- optimistic lock: PATCH sends it in If-Match
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (start_at IS NULL OR end_at IS NULL OR start_at < end_at)
);
CREATE INDEX campaigns_advertiser ON campaigns (advertiser_id);

CREATE TABLE campaign_items (
  campaign_id BIGINT NOT NULL REFERENCES campaigns,
  item_id     INT NOT NULL REFERENCES items,
  PRIMARY KEY (campaign_id, item_id)
);

-- The budget of one campaign on one UTC day. Billing creates the row with the campaign's daily
-- budget at the first charge of the day and locks it (SELECT ... FOR UPDATE) to serialise the
-- charges of the campaign; a budget change made during the day updates today's row, never below
-- what is already spent.
CREATE TABLE campaign_budget_daily (
  campaign_id  BIGINT NOT NULL REFERENCES campaigns,
  day          DATE NOT NULL,
  budget_cents INT NOT NULL CHECK (budget_cents >= 0),
  spent_cents  INT NOT NULL DEFAULT 0 CHECK (spent_cents >= 0),
  PRIMARY KEY (campaign_id, day),
  CHECK (spent_cents <= budget_cents)        -- even a bug cannot bill past the budget
);

-- The charge ledger, append-only: at most one charge per impression (§9.3, business dedup).
-- day is the UTC day the impression was served (from the ad_token), so every click on one
-- impression maps to the same budget row whatever order the clicks are processed in.
CREATE TABLE ad_charges (
  impression_id  TEXT PRIMARY KEY,           -- {request_id}:{position}
  click_event_id UUID NOT NULL,              -- the click that was billed
  campaign_id    BIGINT NOT NULL,
  day            DATE NOT NULL,
  price_cents    INT NOT NULL CHECK (price_cents > 0),  -- auction price (from the ad_token)
  billed_cents   INT NOT NULL CHECK (billed_cents >= 0 AND billed_cents <= price_cents),
  created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (campaign_id, day) REFERENCES campaign_budget_daily
);
CREATE INDEX ad_charges_campaign_day ON ad_charges (campaign_id, day);

-- Every sponsored click billing processed, keyed by event_id: the "already processed" marker
-- (technical dedup, §7.3), written in the charge's transaction. token_status:
--   valid    the token verified; the click was charged or was a repeat click on the impression
--   expired  the token verified but the click arrived after it expired: not billed
--   mismatch the token verified but names another impression, user or item: not billed
--   invalid  the token did not verify: not billed, and its campaign and day are not trusted
CREATE TABLE ad_clicks (
  event_id      UUID PRIMARY KEY,
  impression_id TEXT NOT NULL,
  user_id       BIGINT NOT NULL,
  item_id       INT NOT NULL,
  token_status  TEXT NOT NULL CHECK (token_status IN ('valid', 'expired', 'mismatch', 'invalid')),
  campaign_id   BIGINT,
  day           DATE,
  received_at   TIMESTAMPTZ NOT NULL,        -- when the api received the click
  processed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((token_status = 'invalid') = (campaign_id IS NULL)),
  CHECK ((campaign_id IS NULL) = (day IS NULL))
);
CREATE INDEX ad_clicks_campaign_day ON ad_clicks (campaign_id, day);

-- +goose Down
