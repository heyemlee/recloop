"""Render docs/results/ann.md from the dict built by ml.ann.run (deterministic output)."""

from __future__ import annotations

import numpy as np

BUDGET_MS = 35.0  # SASRec retrieval stage: encode the history + FAISS top-k
TARGETS = (0.95, 0.99)
FAMILIES = ("IVF-Flat", "HNSW", "IVF-PQ", "IVF-PQ + refine")
CPU_LIMIT_US = 1000.0  # Flat's CPU per query we still call cheap (see "When to switch")
UTILIZATION = 0.5


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _us(v: float | None) -> str:
    if v is None:
        return "-"
    if v < 1000:
        return f"{v:.0f} µs" if v >= 10 else f"{v:.1f} µs"
    return f"{v / 1000:.2f} ms" if v < 10_000 else f"{v / 1000:.1f} ms"


def _mb(b: float) -> str:
    mb = b / 1e6
    return f"{mb:.2f} MB" if mb < 10 else f"{mb:.0f} MB"


def _sec(s: float) -> str:
    if s < 0.0005:
        return "<1 ms"
    if s < 0.1:
        return f"{s * 1000:.0f} ms"
    if s < 100:
        return f"{s:.1f} s"
    return f"{s / 60:.1f} min"


def _n(n: float) -> str:
    if n >= 1_000_000:
        return f"{n / 1e6:g}M"
    if n >= 10_000 and n % 1000 == 0:
        return f"{int(n) // 1000}K"
    return f"{int(n):,}"


def _rec(r: dict) -> str:
    return f"{r['recall']:.3f} / {r['recall_p5']:.2f}"


def _settings(r: dict) -> str:
    p = r["params"]
    if r["index"] == "Flat":
        return "exact"
    if r["index"] == "IVF-Flat":
        return f"nlist {p['nlist']}, nprobe {p['nprobe']}"
    if r["index"] == "HNSW":
        return f"M {p['M']}, efC {p['efC']}, efSearch {p['efSearch']}"
    s = f"nlist {p['nlist']}, m {p['m']}, nprobe {p['nprobe']}"
    return s + (f", k_factor {p['k_factor']}" if p["k_factor"] > 1 else "")


def _build(r: dict) -> str:
    if r["index"] == "Flat":
        return _sec(r["add_s"])
    if r["index"] == "HNSW":
        return _sec(r["add_s"])
    return f"{_sec(r['train_s'])} + {_sec(r['add_s'])}"


def cheapest(rows: list[dict], target: float, family: str | None = None) -> dict | None:
    ok = [r for r in rows if r["recall"] >= target and (family is None or r["index"] == family)]
    return min(ok, key=lambda r: (r["p99_us"], r["p50_us"])) if ok else None


def flat_row(scale: dict) -> dict:
    return next(r for r in scale["rows"] if r["index"] == "Flat")


def flat_cost(scales: list[dict]) -> dict:
    """Least-squares fit of Flat's mean / P99 latency = a + b * n over the synthetic sizes."""
    pts = [(s["n"], flat_row(s)) for s in scales if s.get("source") == "mixture"]
    n = np.array([p[0] for p in pts], dtype=np.float64)
    out = {}
    for key in ("mean_us", "p99_us"):
        y = np.array([p[1][key] for p in pts])
        b, a = np.polyfit(n, y, 1)
        out[key] = {"a_us": float(a), "b_ns_per_item": float(b * 1000)}
    return out


def max_items(cost: dict, cpu_us: float) -> float:
    return (cpu_us - cost["a_us"]) / (cost["b_ns_per_item"] / 1000)


# ----------------------------------------------------------------------------------------


def render(out: dict) -> str:
    s = out["setup"]
    scales = [x for x in out["scales"] if "rows" in x]
    lines = [
        "# ANN benchmark and index updates",
        "",
        "<!-- Generated by `make ann` (ml/ann/run.py). Do not edit by hand. -->",
        "",
    ]
    if s["status"] != "final":
        why = "; ".join(s["status_reasons"])
        lines += [
            f"> **Preliminary numbers** ({why}). Latency and build times depend on what else "
            "the machine is doing and are indicative only; recall, list balance and vectors "
            "compared per query do not depend on load. `make ann` on an idle machine gives the "
            "final version of this file.",
            "",
        ]
    lines += [
        "SASRec retrieval scores the user vector against every item vector with an in-process",
        "FAISS index and returns the top items. With 3,459 items that is an exact `IndexFlatIP`",
        "search. This report asks (1) at what catalog size exact search should give way to an",
        "approximate (ANN) index and how to set its parameters, and (2) how to keep an index",
        "current while items are added and removed. Item vectors are synthetic stand-ins with",
        "the cluster structure of the real catalog (64-d, like SASRec's), scaled to 100K and 1M",
        "items.",
        "",
    ]
    lines += _summary(out, scales)
    lines += _setup(out)
    lines += _vectors(out, scales)
    lines += _switch(out, scales)
    lines += _recommendations(scales)
    if out.get("ksweep"):
        lines += _ksweep(out["ksweep"])
    if out.get("incremental"):
        lines += _updates(out["incremental"], s)
    lines += _sweeps(scales)
    lines += _reproduce(out)
    return "\n".join(lines).rstrip() + "\n"


