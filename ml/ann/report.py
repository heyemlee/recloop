def _setup(out: dict) -> list[str]:
    s, m = out["setup"], out["setup"]["machine"]
    cores = (
        f"{m['performance_cores']} performance + {m['efficiency_cores']} efficiency cores"
        if m.get("performance_cores")
        else f"{m['logical_cpus']} CPUs"
    )
    cpu = ", ".join(v for v in (m.get("label"), m.get("model"), m.get("cpu")) if v) or "CPU unknown"
    load = " / ".join(f"{v:.1f}" for v in s["load_average_start"])
    load_end = " / ".join(f"{v:.1f}" for v in s["load_average_end"])
    oh = s["call_overhead_us"]
    return [
        "## Setup",
        "",
        *_table(
            ["", ""],
            [
                ["Machine", f"{cpu}, {cores}, {m['memory_gib']:.0f} GB; {m['os']}"],
                [
                    "State",
                    f"{s['status']}; load average (1 / 5 / 15 min) {load} at the start, "
                    f"{load_end} at the end; power: {m.get('power') or 'unknown'}",
                ],
                [
                    "Software",
                    f"FAISS {s['faiss']} (faiss-cpu wheel, {s['faiss_options']}), "
                    f"numpy {s['numpy']}, scipy {s['scipy']}, Python {s['python']}",
                ],
                [
                    "Latency",
                    f"one query per `index.search` call from Python, {s['search_threads']} "
                    f"thread, wall time around the call; {s['queries']:,} queries per "
                    f"configuration after {s['warmup']} warm-up queries; P50 / P99 per run, "
                    f"median of {s['runs']} runs; garbage collection off while timing"
                    + (
                        "; thread QoS user-interactive (keeps the loop on a performance core)"
                        if s["qos_user_interactive"]
                        else ""
                    )
                    + f". The call itself costs {_us(oh[0])} (P50; a one-vector index)",
                ],
                [
                    "Builds",
                    f"{s['build_threads']} threads; times are wall-clock for train (k-means, PQ) "
                    "and add (assignment, graph construction)",
                ],
                [
                    "Recall",
                    f"recall@{s['k']} against the exact top-{s['k']} by inner product (brute force "
                    "in float64 with numpy); a returned item counts if its score is at least the "
                    f"{s['k']}th best, so ties count. Mean over users, and the 5th percentile "
                    '("mean / P5")',
                ],
                ["Memory", "serialized index size (vectors or codes, ids, graph links)"],
                ["Seed", f"{s['seed']} for the vectors, queries and k-means"],
            ],
        ),
        "",
    ]


def _vectors(out: dict, scales: list[dict]) -> list[str]:
    d, s = out["data"], out["setup"]
    qp = s["query_params"]
    lines = ["## Vectors", ""]
    if "source" not in d:
        lines += [
            f"The embedding file was not available, so item vectors come from a synthetic "
            f"clustered Gaussian ({d['k']} anisotropic clusters on the unit sphere).",
            "",
        ]
    else:
        src = d["source"]
        trials = d["trials"]
        ks = sorted({t["k"] for t in trials})
        regs = sorted({t["reg"] for t in trials})
        cv = {(t["k"], t["reg"]): t["cv_ll"] for t in trials}
        w = d["weights"]
        lines += [
            f"1. **Real vectors.** MiniOneRec's text embeddings of the 3,459 Office items "
            f"(`{src['path']}`, {src['shape'][0]:,} x {src['shape'][1]:,}, SHA-256 "
            f"`{src['sha256'][:16]}...`) are L2-normalized, centered and reduced to 64 "
            f"dimensions by PCA ({d['pca_explained']:.1%} of the variance; the 64 components' "
            f"participation ratio is {d['participation_ratio']:.0f} effective dimensions), "
            "then normalized again.",
            f"2. **Mixture.** A Gaussian mixture with full covariances is fitted to them by EM "
            f"(k-means start). The number of components and the covariance regularization "
            f"(added to the diagonal) are chosen by 5-fold cross-validated log-likelihood: "
            f"**{d['k']} components, regularization {d['reg']:g}**. Component weights range "
            f"from {min(w):.3f} to {max(w):.3f}.",
            "3. **Synthetic catalogs** of any size are drawn from the mixture and L2-normalized "
            "(inner product = cosine). Each item's component plays the role of its category.",
            f"4. **Users.** A user has a history of 1 to {qp['max_len']} items (uniform). Each "
            f"history item comes from the user's home category with probability "
            f"{qp['p_home']}, otherwise from anywhere in the catalog; the user vector is the "
            f"recency-weighted sum (weight {qp['decay']} per step back) of the history's item "
            "vectors, normalized.",
            "",
            "Cross-validated log-likelihood per item (higher is better):",
            "",
            *_table(
                ["components"] + [f"reg {r:g}" for r in regs],
                [
                    [str(k)]
                    + [
                        ("**" + f"{cv[(k, r)]:.1f}" + "**")
                        if (k, r) == (d["k"], d["reg"])
                        else f"{cv[(k, r)]:.1f}"
                        for r in regs
                    ]
                    for k in ks
                ],
            ),
            "",
        ]
        prof = d["profile"]
        lines += [
            "How close neighbours are, real vs. synthetic at the same size (3,459 items): "
            "cosine to the r-th nearest other item, 10th / 50th / 90th percentile over items.",
            "",
            *_table(
                ["r", "real", "synthetic"],
                [
                    [
                        r,
                        " / ".join(f"{v:.2f}" for v in prof["real"][r]),
                        " / ".join(f"{v:.2f}" for v in prof["synthetic"][r]),
                    ]
                    for r in prof["real"]
                ],
            ),  # fmt: skip
            "",
            "The 100th-neighbour similarities match, which is the scale recall@100 works at. The",
            "real catalog has closer nearest neighbours (near-duplicate listings and variants of",
            "one product) that the mixture does not reproduce: within a component, synthetic",
            "items are spread evenly, so neighbourhoods are less distinct than in real data and",
            "the synthetic catalogs are, if anything, harder for an ANN index. The real and the",
            "synthetic 3,459-item catalogs are both benchmarked below as a check.",
            "",
        ]
    lines += [
        *_table(
            ["Catalog", "Items", "Source", "Queries", "Vector digest"],
            [
                [
                    x["name"],
                    f"{x['n']:,}",
                    "real PCA vectors" if x["source"] == "real" else "mixture draw",
                    f"{x['queries']:,}",
                    f"`{x['digest']}`",
                ]
                for x in scales
            ],
        ),  # fmt: skip
        "",
    ]
    lines += _calibration(scales)
    return lines


def _calibration(scales: list[dict]) -> list[str]:
    """Same index settings on the real and the synthetic 3,459-item catalogs."""
    real = next((x for x in scales if x["source"] == "real"), None)
    synth = next(
        (x for x in scales if x["source"] == "mixture" and real and x["n"] == real["n"]), None
    )
    if not (real and synth):
        return []

    def key(r):
        return (r["index"], tuple(sorted(r["params"].items())))

    other = {key(r): r for r in synth["rows"]}
    pairs = [(r, other[key(r)]) for r in real["rows"] if key(r) in other and r["index"] != "Flat"]
    if not pairs:
        return []
    diff = np.array([s["recall"] - r["recall"] for r, s in pairs])
    return [
        f"Check: over the {len(pairs)} IVF and HNSW settings run on both 3,459-item catalogs, "
        f"recall@100 on the synthetic catalog is within {np.abs(diff).max():.3f} of the real "
        f"one (mean difference {diff.mean():+.3f}), so the mixture reproduces how hard the real "
        "vectors are for these indexes at this size.",
        "",
    ]


def _switch(out: dict, scales: list[dict]) -> list[str]:
    synth = [x for x in scales if x["source"] == "mixture"]
    if len(synth) < 2:
        return []
    fit = flat_cost(scales)
    cost = fit["mean_us"]
    rows = []
    for x in scales:
        f = flat_row(x)
        rows.append(
            [
                f"{x['name']} ({x['n']:,})",
                _us(f["p50_us"]),
                _us(f["p99_us"]),
                _us(f["mean_us"]),
                f"{f['p99_us'] / (BUDGET_MS * 1000):.1%}",
                f"{UTILIZATION * 1e6 / f['mean_us']:,.0f}",
            ]
        )
    lines = [
        "## When to switch from Flat",
        "",
        f"The retrieval stage has {BUDGET_MS:.0f} ms of the request's 100 ms deadline, and that "
        "includes encoding the user's history. Flat search is a single pass over all vectors, so "
        "its cost grows linearly with the catalog:",
        "",
        *_table(
            [
                "Catalog",
                "Flat P50",
                "Flat P99",
                "Mean (= CPU per query)",
                "P99 / 35 ms",
                f"Queries/s per core at {UTILIZATION:.0%}",
            ],
            rows,
        ),  # fmt: skip
        "",
        f"A linear fit over the synthetic sizes gives {cost['a_us']:.0f} µs + "
        f"{cost['b_ns_per_item']:.2f} ns per item (mean) and "
        f"{fit['p99_us']['b_ns_per_item']:.2f} ns per item at P99. Latency alone would allow "
        f"millions of items: P99 reaches 10 ms at about "
        f"{_round_items(max_items(fit['p99_us'], 10_000))} items. The limit is CPU: every "
        "request pays the full scan, and the model-server has a few cores. Largest catalog that "
        "keeps Flat's CPU per query within a budget:",
        "",
        *_table(
            ["CPU per query", f"Queries/s per core at {UTILIZATION:.0%}", "Largest Flat catalog"],
            [
                [_us(c), f"{UTILIZATION * 1e6 / c:,.0f}", _round_items(max_items(cost, c))]
                for c in (250.0, 500.0, 1000.0, 2000.0, 5000.0)
            ],
        ),
        "",
        "These are service times of single queries; under concurrent load, queueing adds to "
        "them, which is another reason to keep per-query CPU small.",
        "",
        f"With ~{CPU_LIMIT_US / 1000:.0f} ms per query as the limit (a few hundred requests/s per "
        "core), switch to ANN at roughly "
        f"{_round_items(max_items(cost, CPU_LIMIT_US))} items; below that Flat is exact, needs "
        "no training or tuning, and a new item is just appended. The current catalog (3,459 "
        f"items, {_us(flat_row(scales[0])['p50_us'])} per query) stays on Flat.",
        "",
    ]
    return lines


def _recommendations(scales: list[dict]) -> list[str]:
    lines = [
        "## Recommended settings",
        "",
        "Cheapest configuration (lowest P99) of each index type that reaches the recall "
        'target. Recall is "mean / 5th percentile over users"; build is train + add.',
        "",
    ]
    for target in TARGETS:
        rows = []
        for x in scales:
            fr = flat_row(x)
            rows.append(
                [x["name"], "Flat", "exact", _rec(fr), _us(fr["p50_us"]), _us(fr["p99_us"]),
                 _mb(fr["bytes"]), _build(fr)]
            )  # fmt: skip
            for fam in FAMILIES:
                r = cheapest(x["rows"], target, fam)
                if r:
                    rows.append(
                        [x["name"], fam, _settings(r), _rec(r), _us(r["p50_us"]),
                         _us(r["p99_us"]), _mb(r["bytes"]), _build(r)]
                    )  # fmt: skip
                elif any(rr["index"] == fam for rr in x["rows"]):
                    rows.append([x["name"], fam, f"none reaches {target}", "", "", "", "", ""])
        lines += [
            f"### Recall@100 ≥ {target}",
            "",
            *_table(
                ["Catalog", "Index", "Settings", "Recall", "P50", "P99", "Memory", "Build"],
                rows,
            ),
            "",
        ]
    lines += _rules(scales)
    return lines


def _rules(scales: list[dict]) -> list[str]:
    lines = ["How the parameters behave:", ""]
    largest = max(scales, key=lambda x: x["n"])
    n = largest["n"]
    rows = largest["rows"]
    for x in (x for x in scales if x["n"] >= 100_000):
        ivf = cheapest(x["rows"], TARGETS[-1], "IVF-Flat")
        if ivf:
            nlist = ivf["params"]["nlist"]
            lines.append(
                f"- IVF at {_n(x['n'])}: nlist {nlist} (≈ {nlist / np.sqrt(x['n']):.0f} √n) with "
                f"nprobe {ivf['params']['nprobe']} reaches {ivf['recall']:.3f} while comparing "
                f"{ivf['ndis']:,.0f} vectors per query ({ivf['ndis'] / x['n']:.1%} of the "
                "catalog)."
            )
    per_nlist = []
    for nlist in sorted({r["params"]["nlist"] for r in rows if r["index"] == "IVF-Flat"}):
        sub = [r for r in rows if r["index"] == "IVF-Flat" and r["params"]["nlist"] == nlist]
        best = cheapest(sub, TARGETS[-1])
        reach = (
            f"recall ≥ {TARGETS[-1]} at nprobe {best['params']['nprobe']} (P99 "
            f"{_us(best['p99_us'])})"
            if best
            else f"does not reach {TARGETS[-1]}"
        )
        per_nlist.append(f"nlist {nlist}: trains in {_sec(sub[0]['train_s'])}, {reach}")
    fastest = []
    for x in (x for x in scales if x["n"] >= 100_000):
        ivf = cheapest(x["rows"], TARGETS[-1], "IVF-Flat")
        if ivf:
            fastest.append(f"≈ {ivf['params']['nlist'] / np.sqrt(x['n']):.0f} √n at {_n(x['n'])}")
    lines += [
        f"- IVF nlist at {_n(n)}: " + "; ".join(per_nlist) + ". More lists scan fewer vectors "
        "per probe but need more probes for the same recall, and the coarse quantizer (all "
        "nlist centroids, scanned on every query) and k-means training grow with nlist. The "
        f"fastest nlist for recall ≥ {TARGETS[-1]} was " + " and ".join(fastest) + " (FAISS's "
        "guideline is 4√n to 16√n); FAISS wants at least 39 training points per centroid.",
        "- nprobe trades recall for time; latency follows the vectors compared.",
    ]
    hnsw = [r for r in rows if r["index"] == "HNSW"]
    if hnsw:
        builds = {}
        for r in hnsw:
            builds.setdefault((r["params"]["M"], r["params"]["efC"]), r)
        mem = ", ".join(
            f"M {m}: {_mb(r['bytes'])}" for (m, efc), r in sorted(builds.items()) if efc == 200
        )
        efc_pair = [
            (efc, r) for (m, efc), r in sorted(builds.items()) if m == 32
        ]  # efConstruction at M 32
        ef_ref = 256
        p5 = {
            efc: next(
                (
                    r["recall_p5"]
                    for r in hnsw
                    if r["params"]["M"] == 32
                    and r["params"]["efC"] == efc
                    and r["params"]["efSearch"] == ef_ref
                ),
                None,
            )
            for efc, _ in efc_pair
        }
        line = f"- HNSW at {_n(n)}: memory {mem}."
        if len(efc_pair) == 2 and None not in p5.values():
            (e1, r1), (e2, r2) = efc_pair
            line += (
                f" efConstruction {e1} → {e2} costs {_sec(r1['add_s'])} → {_sec(r2['add_s'])} of "
                f"build time and lifts the worst users (P5 recall at efSearch {ef_ref}: "
                f"{p5[e1]:.2f} → {p5[e2]:.2f})."
            )
        line += (
            " efSearch is the query-time knob; FAISS does not raise it to k: with efSearch < k "
            "it still returns k items, from a shorter search."
        )
        lines.append(line)
    pq = [r for r in rows if r["index"] in ("IVF-PQ", "IVF-PQ + refine")]
    if pq:
        parts = []
        for m in sorted({r["params"]["m"] for r in pq}):
            plain = [r for r in pq if r["index"] == "IVF-PQ" and r["params"]["m"] == m]
            ref = [r for r in pq if r["index"] == "IVF-PQ + refine" and r["params"]["m"] == m]
            top_plain = max(plain, key=lambda r: r["recall"])
            top_ref = max(ref, key=lambda r: r["recall"]) if ref else None
            part = (
                f"m {m} ({m} bytes per vector, {_mb(top_plain['bytes'])}) tops out at "
                f"{top_plain['recall']:.3f}"
            )
            if top_ref:
                part += (
                    f", {top_ref['recall']:.3f} with k_factor {top_ref['params']['k_factor']} "
                    f"re-scoring ({_mb(top_ref['bytes'])})"
                )
            parts.append(part)
        lines.append(
            f"- IVF-PQ at {_n(n)}: " + "; ".join(parts) + ". PQ's distortion caps recall however "
            "many lists are probed; re-scoring PQ candidates with the full vectors "
            "(IndexRefineFlat) recovers IVF-Flat's recall but keeps the full vectors in memory, "
            "so PQ pays only when memory is the constraint."
        )
    return lines + [""]


def _ksweep_reach(rows: list[dict], k: int, family: str, target: float) -> dict | None:
    return cheapest([r for r in rows if r["k"] == k], target, family)


def _ksweep_summary(ks: dict) -> str:
    rows, k_lo, k_hi = ks["rows"], min(ks["sweep"]["ks"]), max(ks["sweep"]["ks"])
    target = TARGETS[-1]
    parts = []
    for family, knob in (("IVF-Flat", "nprobe"), ("HNSW", "efSearch")):
        lo = _ksweep_reach(rows, k_lo, family, target)
        hi = _ksweep_reach(rows, k_hi, family, target)
        if lo and hi and hi["params"][knob] == lo["params"][knob]:
            parts.append(
                f"{family} gets there at the same {knob} {hi['params'][knob]} as for top-{k_lo} "
                f"(P99 {_us(hi['p99_us'])} vs {_us(lo['p99_us'])})"
            )
        elif lo and hi:
            parts.append(
                f"{family} needs {knob} {hi['params'][knob]} instead of {lo['params'][knob]} "
                f"(P99 {_us(hi['p99_us'])} vs {_us(lo['p99_us'])})"
            )
        elif hi:
            parts.append(
                f"{family} gets there at {knob} {hi['params'][knob]} (P99 {_us(hi['p99_us'])})"
            )
        else:
            best = max((r for r in rows if r["k"] == k_hi and r["index"] == family),
                       key=lambda r: r["recall"])  # fmt: skip
            parts.append(
                f"{family} does not get there (best {best['recall']:.3f} at {knob} "
                f"{best['params'][knob]}, P99 {_us(best['p99_us'])})"
            )
    flat = next((r for r in rows if r["index"] == "Flat" and r["k"] == k_hi), None)
    hnsw = _ksweep_reach(rows, k_hi, "HNSW", target)
    slower = (
        f", slower than exact search (Flat P99 {_us(flat['p99_us'])})"
        if flat and hnsw and hnsw["p99_us"] > flat["p99_us"]
        else ""
    )
    return (
        f"- **Top-{k_hi}** (what the retrieval stage asks for), {_n(ks['n'])} items: for recall@"
        f"{k_hi} ≥ {target}, " + "; ".join(parts) + slower + "."
    )


def _ksweep(ks: dict) -> list[str]:
    rows, sweep = ks["rows"], ks["sweep"]
    k_lo, k_hi = min(sweep["ks"]), max(sweep["ks"])
    by = {}
    for r in rows:
        by.setdefault((r["index"], tuple(sorted(r["params"].items()))), {})[r["k"]] = r
    table = []
    for (index, _), per_k in by.items():
        lo, hi = per_k[k_lo], per_k[k_hi]
        table.append(
            [index, _settings(lo), _rec(lo), _us(lo["p50_us"]), _us(lo["p99_us"]),
             _rec(hi), _us(hi["p50_us"]), _us(hi["p99_us"])]
        )  # fmt: skip
    lines = [
        f"## Top-{k_hi}",
        "",
        f"The retrieval stage asks FAISS for the top {k_hi} items; the sweeps above use k = "
        f"{k_lo}. Here the same {_n(ks['n'])}-item indexes (the catalog of the sweep above) are "
        f"searched with k = {k_lo} and k = {k_hi} in turn for every setting, so both columns "
        f"come from the same index under the same conditions. Recall@k is against the exact "
        f"top-k.",
        "",
        *_table(
            [
                "Index",
                "Settings",
                f"k = {k_lo}: recall",
                "P50",
                "P99",
                f"k = {k_hi}: recall",
                "P50",
                "P99",
            ],
            table,
        ),  # fmt: skip
        "",
    ]
    for target in TARGETS:
        parts = []
        for family, knob in (("IVF-Flat", "nprobe"), ("HNSW", "efSearch")):
            got = [(k, _ksweep_reach(rows, k, family, target)) for k in (k_lo, k_hi)]
            parts.append(
                f"{family}: "
                + ", ".join(
                    f"k = {k} at {knob} {r['params'][knob]} (P99 {_us(r['p99_us'])})"
                    if r
                    else f"k = {k} not reached"
                    for k, r in got
                )
            )
        lines.append(f"- Recall ≥ {target}: " + "; ".join(parts) + ".")
    flat = by.get(("Flat", ()), {})
    if flat:
        lines.append(
            f"- Flat: P50 {_us(flat[k_lo]['p50_us'])} at k = {k_lo}, "
            f"{_us(flat[k_hi]['p50_us'])} at k = {k_hi} (the scan is the same; only the "
            "result heap grows)."
        )
    for family, knob in (("IVF-Flat", "nprobe"), ("HNSW", "efSearch")):
        pairs = [(v[k_lo], v[k_hi]) for (index, _), v in by.items() if index == family]
        if not pairs:
            continue
        drop = max(lo["recall"] - hi["recall"] for lo, hi in pairs)
        time = float(np.median([hi["p50_us"] / lo["p50_us"] for lo, hi in pairs]))
        line = (
            f"- {family} at equal settings: recall@{k_hi} trails recall@{k_lo} by at most "
            f"{drop:.3f}, and P50 changes by {time - 1:+.0%} (median over settings): the work is "
            "the scan or the walk, not the longer result list."
        )
        if family == "HNSW":
            short = [(lo, hi) for lo, hi in pairs if lo["params"][knob] < k_hi]
            if short:
                lo, hi = min(short, key=lambda x: x[0]["params"][knob])
                line += (
                    f" With efSearch below k the candidate list is shorter than the result: at "
                    f"efSearch {lo['params'][knob]}, recall@{k_hi} is {hi['recall']:.3f} against "
                    f"{lo['recall']:.3f} at k = {k_lo}; keep efSearch ≥ k."
                )
        lines.append(line)
    return lines + [""]


