def _summary(out: dict, scales: list[dict]) -> list[str]:
    lines = ["## Summary", ""]
    synth = [x for x in scales if x["source"] == "mixture"]
    if len(synth) >= 2:
        cost = flat_cost(scales)["mean_us"]
        largest = synth[-1]
        fr = flat_row(largest)
        lines.append(
            "- **Flat** costs about "
            f"{cost['b_ns_per_item']:.1f} ns per item per query on one core: "
            + ", ".join(f"{_us(flat_row(x)['p50_us'])} at {_n(x['n'])}" for x in synth)
            + f" (P50). At {_n(largest['n'])} items its P99 ({_us(fr['p99_us'])}) still fits "
            f"the {BUDGET_MS:.0f} ms retrieval budget, but each query takes "
            f"{_us(fr['mean_us'])} of CPU, about {UTILIZATION * 1e6 / fr['mean_us']:.0f} "
            f"queries/s per core at {UTILIZATION:.0%} utilization."
        )
        n_switch = max_items(cost, CPU_LIMIT_US)
        lines.append(
            f"- **When to switch**: once Flat needs more than ~{CPU_LIMIT_US / 1000:.0f} ms of "
            f"CPU per query (≈{_round_items(n_switch)} items at 64-d), use an ANN index; below "
            "that Flat is exact, has no parameters and no training, and adding an item is an "
            "append. The current catalog (3,459 items) stays on Flat."
        )
        for target in TARGETS:
            best = cheapest(largest["rows"], target)
            if best:
                lines.append(
                    f"- **Recall@{out['setup']['k']} ≥ {target}** at {_n(largest['n'])}: "
                    f"{best['index']} ({_settings(best)}) with P99 {_us(best['p99_us'])}, "
                    f"{_mb(best['bytes'])}, recall {best['recall']:.3f} "
                    f"(5th percentile over users {best['recall_p5']:.2f})."
                )
        lines.append(_ivf_vs_hnsw(largest, out["setup"]["k"]))
    if out.get("ksweep"):
        lines.append(_ksweep_summary(out["ksweep"]))
    inc = out.get("incremental")
    if inc:
        cps = inc["checkpoints"]
        first, last = cps[0], cps[-1]
        bi, bl = first["ivf_incr"]["balance"], last["ivf_incr"]["balance"]
        rb = last["ivf_rebuilt"]
        gi, gr = last["ivf_incr"]["groups"]["new"], rb["groups"]["new"]
        lines.append(
            f"- **IVF with new categories added incrementally**: after "
            f"{last['new_items']:,} new-category items the inverted lists' imbalance factor "
            f"went from {bi['imbalance']:.2f} to {bl['imbalance']:.2f} (largest list "
            f"{bi['max_over_mean']:.1f}x → {bl['max_over_mean']:.1f}x the mean). New-category "
            f"users compare {gi['ndis'] / gr['ndis']:.1f}x as many vectors as on a rebuilt "
            f"index (P99 {_us(gi['p99_us'])} vs {_us(gr['p99_us'])}) and get recall "
            f"{_rec(gi)} instead of {_rec(gr)} (mean / P5). A full rebuild of "
            f"{last['items']:,} items takes {_sec(rb['train_s'] + rb['add_s'])} and brings the "
            f"imbalance back to {rb['balance']['imbalance']:.2f}."
        )
        lines.append(_hnsw_update_sentence(inc))
        lines.append(
            "- **In production**: add new items to the serving index as they arrive, rebuild "
            "from scratch on a schedule (and when the list imbalance or the golden-query recall "
            "crosses a threshold), and ship each rebuilt index as a new bundle version: load it "
            "next to the current one, check golden-query recall against exact search, switch "
            "atomically, keep the old version for rollback."
        )
    return lines + [""]


def _round_items(n: float) -> str:
    if n <= 0:
        return "0"
    mag = 10 ** int(np.floor(np.log10(n)))
    v = round(n / mag * 2) / 2 * mag  # 1 or 2 significant half-steps
    return _n(int(v)) if v >= 10_000 else f"{int(v):,}"


def _ivf_vs_hnsw(scale: dict, k: int) -> str:
    """Compare the two index types at the largest catalog (data-driven sentence)."""
    rows = scale["rows"]
    parts = []
    for target in TARGETS:
        ivf, hnsw = cheapest(rows, target, "IVF-Flat"), cheapest(rows, target, "HNSW")
        if ivf and hnsw:
            parts.append(
                f"for recall ≥ {target} IVF-Flat's P99 is {_us(ivf['p99_us'])} against "
                f"HNSW's {_us(hnsw['p99_us'])}"
            )
        elif ivf:
            best = max((r for r in rows if r["index"] == "HNSW"), key=lambda r: r["recall"])
            parts.append(
                f"for recall ≥ {target} IVF-Flat needs P99 {_us(ivf['p99_us'])}, while no HNSW "
                f"setting in the sweep gets there (best {np.floor(best['recall'] * 1e4) / 1e4:.4f} at "
                f"{_settings(best)}, P99 {_us(best['p99_us'])})"
            )
    if not parts:
        return ""
    hnsw_rows = [r for r in rows if r["index"] == "HNSW"]
    top = max(hnsw_rows, key=lambda r: r["recall"])
    ivf_hi = cheapest(rows, TARGETS[-1], "IVF-Flat")
    tail = (
        f" HNSW's shortfall is a tail that more search does not remove: at {_settings(top)}, "
        f"{top['recall_lt_0.9']:.1%} of users still get recall below 0.9"
    )
    if top.get("span_lt_0.9") is not None:
        tail += (
            f"; their exact top-{k} spans a median of {top['span_lt_0.9']:.0f} categories "
            f"against {scale['span_median']:.0f} for all users, i.e. they sit between clusters"
        )
    if ivf_hi:
        tail += (
            f". IVF's coarse step probes cells on both sides: at {_settings(ivf_hi)}, "
            f"{ivf_hi['recall_lt_0.9']:.1%} of users are below 0.9"
        )
    return (
        f"- **IVF vs HNSW at k = {k}** ({_n(scale['n'])} items): "
        + "; ".join(parts)
        + "."
        + tail
        + "."
    )


def _deletion_rows(inc: dict, pattern: str) -> list[dict]:
    return [r for r in inc["deletion"]["rows"] if r["pattern"] == pattern]


def _hnsw_update_sentence(inc: dict) -> str:
    last = inc["checkpoints"][-1]
    hi, hr = last["hnsw_incr"]["groups"], inc["hnsw_rebuilt"]["groups"]
    gap = max(abs(hi[g]["recall"] - hr[g]["recall"]) for g in ("old", "new"))
    adds = (
        "keeps its recall as items are added"
        if gap <= 0.01
        else f"loses up to {gap:.3f} recall to a rebuilt graph as items are added"
    )
    text = (
        f"- **HNSW** {adds}: after the last batch {hi['old']['recall']:.3f} / "
        f"{hi['new']['recall']:.3f} (old / new-category users) vs {hr['old']['recall']:.3f} / "
        f"{hr['new']['recall']:.3f} for a graph built from scratch "
        f"({_sec(inc['hnsw_rebuilt']['build_s'])}). It cannot delete, and filtering deleted "
        "items at search time holds up only when deletions are scattered:"
    )
    rand, cat = _deletion_rows(inc, "random"), _deletion_rows(inc, "category")
    if rand:
        r = rand[-1]
        text += (
            f" with {r['deleted'] / r['items']:.0%} of the items deleted at random, recall is "
            f"{_rec(r['filter'])} (rebuilt: {_rec(r['rebuild'])})"
        )
    if cat:
        c = cat[0]
        text += (
            f"; deleting whole categories ({c['deleted'] / c['items']:.0%} of the items) drops "
            f"it to {_rec(c['filter'])}, and a rebuild ({_sec(c['rebuild']['build_s'])}) "
            f"restores {_rec(c['rebuild'])}"
        )
    return text + "."


