def _update_conclusions(inc: dict) -> list[str]:
    cps = inc["checkpoints"]
    first, last = cps[0], cps[-1]
    b0, b1 = first["ivf_incr"]["balance"], last["ivf_incr"]["balance"]
    ctrl = last["ivf_control"]["balance"]
    gi0, gi = first["ivf_incr"]["groups"]["new"], last["ivf_incr"]["groups"]["new"]
    gr = last["ivf_rebuilt"]["groups"]["new"]
    rb = last["ivf_rebuilt"]
    drift_grows = b1["imbalance"] - b0["imbalance"] > 2 * max(
        ctrl["imbalance"] - b0["imbalance"], 0.05
    )
    lines = ["### What this means for serving", ""]
    if drift_grows:
        lines.append(
            f"- Incremental adds keep an IVF index working but let it decay under drift: new "
            f"categories land in the few old cells nearest to them, the imbalance factor grows "
            f"({b0['imbalance']:.2f} → {b1['imbalance']:.2f}) and so do the vectors a "
            f"new-category query compares ({gi0['ndis']:,.0f} → {gi['ndis']:,.0f}; "
            f"{gr['ndis']:,.0f} on a rebuilt index), while recall for those users stays low "
            f"({_rec(gi)} vs {_rec(gr)} rebuilt). The no-drift control stays at "
            f"{ctrl['imbalance']:.2f}: adding more of the same distribution is harmless; new "
            "regions of the space are what the old centroids cannot cover."
        )
    else:
        lines.append(
            f"- Incremental adds barely moved the IVF lists here (imbalance {b0['imbalance']:.2f} "
            f"→ {b1['imbalance']:.2f}; control {ctrl['imbalance']:.2f})."
        )
    lines += [
        f"- A full IVF rebuild (k-means + add) of {last['items']:,} items takes "
        f"{_sec(rb['train_s'] + rb['add_s'])} with {inc['plan']['nlist']} lists: cheap enough "
        f"to run on a schedule (nightly) and on demand. In between, adding a "
        f"{inc['plan']['batch_size']:,}-item batch to the serving index takes "
        f"{_sec(last['ivf_incr']['add_s'])} (IVF) or {_sec(last['hnsw_incr']['add_s'])} "
        "(HNSW).",
        "- Rebuild triggers that are cheap to watch: the imbalance factor of the inverted "
        "lists (computed from list sizes, no queries), and recall on a fixed golden query set "
        "against exact search.",
        "- HNSW handles additions without retraining; deletions are its weak spot. Scattered "
        "deletions can be filtered with an IDSelector (memory and walk stay as large as the "
        "original graph) until a scheduled rebuild; removing a whole category needs a rebuild "
        "before (or with) the removal. IVF can remove ids in place.",
        "- A rebuilt index is a new version: build it offline next to the serving one, check "
        "golden-query recall against Flat, switch the pointer atomically, and keep the previous "
        "version loaded for rollback. Items added after the rebuild's snapshot are added to the "
        "new index before the switch, so nothing is lost between versions.",
        "",
    ]
    return lines


