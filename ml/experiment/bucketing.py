"""Experiment bucketing, the Python twin of serving/internal/experiment (design §8).

    bucket = xxhash64(layer_salt + ":" + unit_id) % 1000

xxhash64 with seed 0, on the UTF-8 bytes. Python's hash() and Go's hash/maphash are seeded per
process and must not be used. Offline analysis (re-salting for A/A checks, the simulator) uses
this module; testdata/bucket_vectors.json pins it to the Go implementation.

Usage: python -m ml.experiment.bucketing --write-vectors testdata/bucket_vectors.json
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import xxhash

BUCKETS = 1000
LAYERS = ("recall", "rank", "ads", "agent")
SALTS = {"recall": "recall-v1", "rank": "rank-v1", "ads": "ads-v1", "agent": "agent-v1"}


def xxh64(text: str) -> int:
    return xxhash.xxh64_intdigest(text.encode("utf-8"), seed=0)


def bucket(salt: str, unit: str) -> int:
    return xxh64(f"{salt}:{unit}") % BUCKETS


def vectors() -> dict:
    """Shared test vectors: reference hashes, every layer for a range of users, edge cases."""
    # Published xxHash64 values (seed 0) anchor the hash itself, independent of both ports.
    reference = [
        {"input": "", "xxh64": "ef46db3751d8e999"},
        {"input": "a", "xxh64": "d24ec4f1a98c6e5b"},
        {"input": "abc", "xxh64": "44bc2cf5ad770999"},
    ]
    for r in reference:
        if f"{xxh64(r['input']):016x}" != r["xxh64"]:
            raise SystemExit(f"xxh64({r['input']!r}) mismatch: the xxhash package is broken")
    units = [str(u) for u in (0, 1, 2, 7, 42, 99, 1000, 8327, 123456789, 9223372036854775807)]
    units += [str(u) for u in range(100, 140)]
    units += ["", "device-3f2a9c", "user:42", "ünïcødé-用户", "x" * 300]
    cases = []
    for layer in LAYERS:
        for unit in units:
            key = f"{SALTS[layer]}:{unit}"
            cases.append(
                {
                    "salt": SALTS[layer],
                    "unit": unit,
                    "xxh64": f"{xxh64(key):016x}",
                    "bucket": bucket(SALTS[layer], unit),
                }
            )
    return {
        "description": "bucket = xxhash64(salt + ':' + unit) % 1000, seed 0, UTF-8; "
        "generated by ml/experiment/bucketing.py, checked by Go and Python tests",
        "buckets": BUCKETS,
        "salts": SALTS,
        "reference": reference,
        "cases": cases,
    }


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--write-vectors", type=Path, required=True)
    args = parser.parse_args(argv)
    args.write_vectors.write_text(json.dumps(vectors(), indent=2, ensure_ascii=False) + "\n")
    print(f"wrote {args.write_vectors}")


if __name__ == "__main__":
    main()
