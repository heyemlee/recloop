"""Render docs/results/minionerec.md from the dict built by ml.eval.minionerec (deterministic)."""

from __future__ import annotations

from ml.eval import metrics
from ml.eval.machine import BUSY_LOAD
from ml.eval.minionerec import NAME, REFERENCES, SEGMENT_METRICS
from ml.eval.report import _ci, _signed, _table

METRIC_NAMES = [f"HR@{k}" for k in metrics.KS] + [f"NDCG@{k}" for k in metrics.KS]
MODELS = ("Pop", "ItemCF", "SASRec", NAME)
SEGMENT_TITLES = {
    "history": "History length",
    "popularity": "Target popularity",
    "category": "Target category",
    "day": "Target day",
}


def _gib(n: float | None) -> str:
    return "n/a" if not n else f"{n / 2**30:.1f} GiB"


def _bytes(n: int) -> str:
    return f"{n / 2**30:.1f} GiB" if n >= 2**30 else f"{n / 2**20:,.0f} MiB"


def _ms(s: float) -> str:
    return f"{s * 1e3:,.0f} ms" if s >= 0.0995 else f"{s * 1e3:.2f} ms"


def _hours(s: float) -> str:
    return f"{s / 3600:.1f} h" if s >= 3600 else f"{s / 60:.0f} min"


def render(out: dict) -> str:
    main = out["runs"][out["main_run"]]
    lines = [
        "# MiniOneRec",
        "",
        "<!-- Generated by `make minionerec` (ml/eval/minionerec.py). Do not edit by hand. -->",
        "",
    ]
    if out["status"] != "final":
        reasons = "; ".join(out["status_reasons"])
        lines += [
            f"> **Preliminary.** {reasons[:1].upper() + reasons[1:]}. Intervals are wide and the "
            "segment and paired results are indicative only; `make minionerec-gen` on the full "
            "test split replaces them.",
            "",
        ]
    lines += [
        "MiniOneRec (generative retrieval: a Qwen2.5-1.5B-Instruct model fine-tuned to emit an",
        "item's three-token semantic ID, decoded with beam search constrained to the catalog's",
        "SIDs), run with its published Office checkpoint on this Mac's GPU, then scored on the",
        "same split and with the same metric code as Pop, ItemCF and SASRec in",
        "[offline.md](offline.md). The questions: does the published result reproduce, which",
        "users does it help, and what does a request cost.",
        "",
    ]
    lines += _setup_section(out, main)
    lines += _repro_section(out, main)
    lines += _comparison_section(out, main)
    if "segments" in main:
        lines += _segment_section(out, main)
    lines += _cost_section(out)
    lines += _agreement_section(out)
    lines += _runs_section(out)
    lines += _provenance_section()
    return "\n".join(lines) + "\n"


def _shards_text(st: dict) -> str:
    n = st.get("shards", 1)
    if n > 1:
        return (
            f"Shards: evaluate.sh's {n} (split.py's boundaries), one after another on the one "
            "GPU, joined by merge.py. "
        )
    return "Shards: one (evaluate.sh runs 8, one per GPU). "


def _attention_text(st: dict) -> str:
    impl = st.get("attn_implementation") or "transformers' default (sdpa)"
    if impl != "eager":
        return f"Attention: {impl}"
    return (
        "Attention: transformers' eager implementation. On MPS, PyTorch's "
        "scaled_dot_product_attention returns NaN for the pad rows of a left-padded batch, and "
        "the NaN spreads to the whole sample, which then decodes no SID (see "
        "`minionerec/upstream.py`)"
    )


def _setup_section(out: dict, main: dict) -> list[str]:
    s = main["summary"]
    st, v, m = s["settings"], s["versions"], s["machine"]
    sel = s["selection"]
    samples = (
        f"all {out['test_samples']:,} test samples ({out['test_users']:,} users)"
        if sel == "all"
        else f"{s['samples']:,} of {out['test_samples']:,} test samples: every sample of "
        f"{sel['users']:,} random test users (seed {sel['seed']})"
    )
    b = out["bootstrap"]
    return [
        "## Setup",
        "",
        *_table(
            ["", ""],
            [
                [
                    "Checkpoint",
                    "MiniOneRec `Office_ckpt` (Hugging Face `kkknight/MiniOneRec` @ 365a03fc): "
                    "Qwen2.5-1.5B-Instruct after SFT and GRPO, saved at RL step 1,038 of 3,456 "
                    "(its trainer_state.json); bfloat16, 3.56 GB",
                ],
                [
                    "Code",
                    "MiniOneRec's own `evaluate.py` (third_party/MiniOneRec @ 0cbd94de) with "
                    "[a patch for Apple Silicon](../../minionerec/evaluate.py.patch): the device "
                    "is `mps` when there is no CUDA, `import bitsandbytes` (CUDA-only, unused) is "
                    "dropped, the model is loaded in a dtype and with an attention implementation "
                    "given on the command line, and every batch is timed. Prompts, the SID prefix "
                    "tree and the constrained beam search run as published. "
                    + _shards_text(st)
                    + _attention_text(st),
                ],
                [
                    "Generation",
                    f"{st['num_beams']} beams, all returned; batch {st['batch_size']}; length "
                    f"penalty {st['length_penalty']}; at most {st['max_new_tokens']} new tokens "
                    + (
                        "(evaluate.sh's settings)"
                        if (st["num_beams"], st["batch_size"]) == (50, 8)
                        else "(evaluate.sh: 50 beams, batch 8)"
                    ),
                ],
                [
                    "Hardware",
                    f"{m['chip']}, {m['gpu_cores']}-core GPU, {m['memory_gib']:.0f} GB unified "
                    f"memory, {m['os']}; device `{s['device']}`; PyTorch {v['torch']}, transformers "
                    f"{v['transformers']} (MiniOneRec's pinned versions); {st['dtype']}, "
                    f"{st.get('attn_implementation') or 'sdpa'} attention",
                ],
                ["Samples", samples],
                [
                    "Metrics",
                    "HR@K and NDCG@K, K = 3, 5, 10, as in offline.md. **Item rule** (main): a "
                    "generated SID stands for every item that has it, in the tie order "
                    "(training popularity, then item_id), so the 15 pairs of items that share a "
                    "SID take two ranks; **SID rule**: the rank of the target's SID among the "
                    "beams, which is what MiniOneRec's calc.py computes",
                ],
                [
                    "Baselines",
                    "Pop, ItemCF and SASRec exactly as in offline.md (train rows only, tuned on "
                    "validation), scored on the same samples",
                ],
                [
                    "Intervals",
                    f"95%, user-level bootstrap: {b['B']:,} replicates, seed {b['seed']}; the "
                    "same replicates for every model, so paired differences are comparable"
                    + (
                        " and the full-split replicates are those of offline.md"
                        if sel == "all"
                        else ""
                    ),
                ],
            ],
        ),
        "",
    ]


def _repro_section(out: dict, main: dict) -> list[str]:
    r = main["reproduction"]
    comp = main["comparison"]["models"][NAME]
    paper, own = r["paper"], r["calc_py"]
    names = [m for m in METRIC_NAMES if m in own]
    rows = [
        ["Paper, Table 1: MiniOneRec", "as reported"] + [f"{paper[m]:.4f}" for m in names],
        ["Our MPS generations", "calc.py (its own code)"] + [f"{own[m]:.4f}" for m in names],
        ["Our MPS generations", "ours, SID rule"] + [_ci(comp["sid"][m]) for m in names],
        ["Our MPS generations", "ours, item rule"] + [_ci(comp["item"][m]) for m in names],
    ]
    full = main["summary"]["selection"] == "all"
    hr_d, nd_d = r["difference"]["HR@10"], r["difference"]["NDCG@10"]
    inside = r["paper_inside_interval"]
    check = main["calc_py"]
    if full:
        verdict = (
            ("**Reproduced.**" if r["reproduced"] else "**Not reproduced.**")
            + f" calc.py on our generations differs from the paper by {hr_d:+.4f} HR@10 and "
            + (
                f"{nd_d:+.4f} NDCG@10; the paper's HR@10 is "
                f"{'inside' if inside['HR@10'] else 'outside'} and its NDCG@10 "
                f"{'inside' if inside['NDCG@10'] else 'outside'} our 95% intervals."
            )
        )
    else:
        verdict = (
            f"On this subset calc.py differs from the paper by {hr_d:+.4f} HR@10 and "
            f"{nd_d:+.4f} NDCG@10. A subset cannot confirm the reproduction: the paper's numbers "
            "are for the whole test split, and the interval here is several times wider."
        )
    return [
        "## Reproduction",
        "",
        f"{r['paper_source']} reports MiniOneRec on this split, scored by its calc.py. The same",
        "calc.py, unmodified, on our generations:",
        "",
        *_table(["Model", "Metrics"] + names, rows),
        "",
        f"- {verdict}",
        f"- Constrained decoding: calc.py counted {check['invalid_predictions']} generated SIDs "
        "that are not in the catalog (its CC; MiniOneRec's README asks to check that it is 0, "
        "since a non-zero count means the constraint did not hold).",
        "- Cross-check: our SID-rule numbers "
        + (
            "equal calc.py's at every K it prints (K up to the beam width)."
            if check["ok"]
            else "**differ** from calc.py's; see artifacts/eval/minionerec.json."
        ),
        "- Same samples, other hardware: MiniOneRec's evaluation runs bfloat16 on CUDA GPUs. "
        f"Beam search keeps the {main['summary']['settings']['num_beams']} best partial SIDs at "
        "every step, so rounding differences can swap near-tied beams and move a target in or "
        "out of the top K.",
        "",
    ]


def _comparison_section(out: dict, main: dict) -> list[str]:
    comp = main["comparison"]
    lines = [
        "## Compared with Pop, ItemCF and SASRec",
        "",
        "Item rule (main):",
        "",
        *_table(
            ["Model"] + METRIC_NAMES,
            [[n] + [_ci(comp["models"][n]["item"][m]) for m in METRIC_NAMES] for n in MODELS],
        ),
        "",
        "SID rule:",
        "",
        *_table(
            ["Model"] + METRIC_NAMES,
            [[n] + [_ci(comp["models"][n]["sid"][m]) for m in METRIC_NAMES] for n in MODELS],
        ),
        "",
        "Paired differences (same bootstrap replicates for both models):",
        "",
        *_table(
            ["Difference", "Rule"] + METRIC_NAMES,
            [
                [pair, rule] + [_signed(d[rule][m]) for m in METRIC_NAMES]
                for pair, d in comp["pairs"].items()
                for rule in ("item", "sid")
            ],
        ),
        "",
        "LightGBM (M4) is added to this table when it exists.",
        "",
    ]
    return lines


def _segment_section(out: dict, main: dict) -> list[str]:
    seg, info = main["segments"], out["segment_info"]
    lines = [
        "## Which users it helps",
        "",
        "Item rule, intervals from a user-level bootstrap inside each group (the same replicates",
        "for every model of a group). The hypothesis was that semantic IDs, built from item text,",
        "help most on long-tail targets and short histories; the segments test it:",
        "",
        "- **History length**: 1-3 or 4-10 items before the target (the window is at most 10).",
        f"- **Target popularity**: head = the {info['head_share_of_items']:.1%} of items with at "
        f"least {info['head_min_train_interactions']:.0f} training interactions (the top 20% "
        f"by count, ties included; {info['head_share_of_train_interactions']:.1%} of all "
        f"training interactions); tail = the rest. "
        f"{info['targets_never_seen_in_training']} test targets never occur in training.",
        f"- **Target category**: level {info['category_level']} of the Amazon category path "
        f"({info['categories']} values, e.g. Paper, Printer Ink & Toner, Writing & Correction "
        "Supplies); cross-category = the target's category is not the category of any history "
        f"item. {info['targets_without_category']} targets have no level-"
        f"{info['category_level']} category and count as the category 'unknown'.",
        "- **Target day**: reviewed on the same day as the last history item, or later (the "
        "split offline.md reports on).",
        "",
    ]
    lines += _findings(main)
    for metric in SEGMENT_METRICS:
        rows = []
        for key, s in seg.items():
            for label, g in s["groups"].items():
                if g["models"] is None:
                    rows.append([SEGMENT_TITLES[key], label, "0"] + ["-"] * 6)
                    continue
                rows.append(
                    [SEGMENT_TITLES[key], label, f"{g['samples']:,}"]
                    + [_ci(g["models"][n][metric]) for n in MODELS]
                    + [_signed(g["pairs"][f"{NAME} - {ref}"][metric]) for ref in REFERENCES]
                )
        lines += [
            f"{metric}:",
            "",
            *_table(
                ["Segment", "Group", "Samples", *MODELS]
                + [f"{NAME} - {ref}" for ref in REFERENCES],
                rows,
            ),
            "",
        ]
    lines += _contrast_table(seg)
    return lines


def _versus_sasrec(cell: dict) -> str:
    lo, hi = cell["ci"]
    if lo > 0:
        return "higher than SASRec's"
    if hi < 0:
        return "lower than SASRec's"
    return "not significantly different from SASRec's"


def _findings(main: dict) -> list[str]:
    """One generated sentence per segmentation: MiniOneRec - SASRec in each group, and whether
    the gap between the groups is significant."""
    ref = f"{NAME} - SASRec"
    overall = main["comparison"]["pairs"][ref]["item"]["HR@10"]
    lines = [
        'Findings (HR@10, item rule; "significant" = the 95% interval excludes 0):',
        "",
        f"- **All samples**: {NAME}'s HR@10 is {_versus_sasrec(overall)} ({_signed(overall)}).",
    ]
    for key, s in main["segments"].items():
        c = s["contrast"]
        if c is None:
            continue
        a, b = c["groups"]
        ga, gb = s["groups"][a]["pairs"][ref]["HR@10"], s["groups"][b]["pairs"][ref]["HR@10"]
        gap = c["pairs"][ref]["HR@10"]
        verdict = (
            f"the difference is significantly larger on {a}"
            if gap["ci"][0] > 0
            else f"the difference is significantly larger on {b}"
            if gap["ci"][1] < 0
            else "the two groups do not differ significantly"
        )
        lines.append(
            f"- **{SEGMENT_TITLES[key]}**: {NAME} - SASRec is {_signed(ga)} on {a} and "
            f"{_signed(gb)} on {b} ({a} minus {b}: {_signed(gap)}); {verdict}."
        )
    lines.append("")
    return lines


def _contrast_table(seg: dict) -> list[str]:
    rows = []
    for key, s in seg.items():
        c = s["contrast"]
        if c is None:
            continue
        a, b = c["groups"]
        rows.append(
            [SEGMENT_TITLES[key], f"{a} minus {b}"]
            + [
                _signed(c["pairs"][f"{NAME} - {ref}"][m])
                for ref in REFERENCES
                for m in SEGMENT_METRICS
            ]
        )
    if not rows:
        return []
    return [
        "Between the two groups of a segment: (MiniOneRec - reference) in the first group minus "
        "the same in the second, with a joint user-level bootstrap over all samples (a user can "
        "have samples in both groups):",
        "",
        *_table(
            ["Segment", "Contrast"]
            + [f"{NAME} - {ref}, {m}" for ref in REFERENCES for m in SEGMENT_METRICS],
            rows,
        ),
        "",
    ]


def _cost_section(out: dict) -> list[str]:
    cost = out["cost"]
    main = out["runs"][out["main_run"]]["summary"]
    lines = ["## Cost", ""]
    lines.append(
        f"The {'full' if main['selection'] == 'all' else 'main'} run generated "
        f"{main['samples']:,} samples in {_hours(main['generate_seconds'])} at "
        f"{main['settings']['num_beams']} beams and batch {main['settings']['batch_size']}: "
        f"{main['seconds_per_sample']:.2f} s per sample, i.e. "
        f"{1000 * main['seconds_per_sample'] / 60:.0f} min of this Mac's GPU per 1,000 users; "
        f"peak memory footprint {_gib(main['peak_footprint'])}. The 1-minute load average was "
        f"at most {main['loadavg_start']:.1f} when a shard started"
        + (
            "."
            if main["loadavg_start"] <= BUSY_LOAD
            else f" (above {BUSY_LOAD:g}: the machine was busy, so these timings are indicative)."
        )
        + _swap_sentence(main.get("swapped_out_bytes"))
    )
    lines.append("")
    if cost is None:
        lines += [
            "Latency, throughput and memory per beam width have not been measured yet "
            "(`make minionerec-cost`, on an idle machine).",
            "",
        ]
        return lines
    flagged = [c for c in cost["configs"].values() if _busy(c) or _disturbed(c)]
    if flagged:
        lines += [
            f"> **Preliminary timings.** {len(flagged)} of {len(cost['configs'])} configurations "
            f"started with a load average above {BUSY_LOAD:g} or ran while another Docker "
            "container ran; rerun `make minionerec-cost` on an idle machine.",
            "",
        ]
    m = cost["machine"]
    devices = sorted({c["device"] for c in cost["configs"].values()})
    where = (
        f"the {m['gpu_cores']}-core GPU (MPS)"
        if devices == ["mps"]
        else "device " + ", ".join(f"`{d}`" for d in devices)
    )
    lines += [
        f"One test sample per user, {cost['users']} random users; MiniOneRec on {where} in "
        f"{cost['dtype']}, SASRec on the CPU ({m['chip']}, "
        f"{m['performance_cores']} performance + {m['efficiency_cores']} efficiency cores). A "
        "request at batch 1 is one user's recommendation; per-call times leave out each "
        "process's first calls (Metal kernel compilation). Memory is the process's physical "
        "footprint (Activity Monitor's figure, which includes what is allocated on the GPU), "
        "with the model weights loaded. Each configuration started when the 1-minute load "
        f"average was below {BUSY_LOAD:g} and no Docker container ran; `docker ps` was checked "
        "every 10 s while it ran, and a configuration during which a container ran was run once "
        "more. The load column is the 1-minute load average at its start and end.",
        "",
    ]
    rows = []
    generate = [c for c in cost["configs"].values() if c["max_new_tokens"] > 1]
    for c in sorted(generate, key=lambda c: (c["num_beams"], c["batch_size"])):
        pc = c["per_call"]
        rows.append(
            [
                f"{NAME}, {c['num_beams']} beams" + (" †" if _disturbed(c) else ""),
                str(c["batch_size"]),
                _ms(pc["p50"]),
                _ms(pc["p90"]),
                _ms(pc["p99"]),
                f"{c['samples_per_second']:.2f}",
                _gib(c["peak_footprint"]),
                f"{c['loadavg_start']:.1f} / {c['loadavg_end']:.1f}",
            ]
        )
    sasrec = cost.get("sasrec")
    if sasrec:
        for r in sasrec["runs"]:
            pc = r["per_call"]
            rows.append(
                [
                    f"SASRec, PyTorch CPU, {r['threads']} thread{'s' if r['threads'] > 1 else ''}"
                    + (" †" if _disturbed(sasrec) else ""),
                    str(r["batch_size"]),
                    _ms(pc["p50"]),
                    _ms(pc["p90"]),
                    _ms(pc["p99"]),
                    f"{r['samples_per_second']:,.0f}",
                    _gib((sasrec.get("footprint") or {}).get("peak")),
                    f"{sasrec['loadavg_start'][0]:.1f} / {sasrec['loadavg_end'][0]:.1f}",
                ]
            )
    lines += _table(
        [
            "Model",
            "Batch",
            "P50 per call",
            "P90",
            "P99",
            "Users per second",
            "Peak memory",
            "Load, start / end",
        ],
        rows,
    )
    lines.append("")
    lines += _quiet_notes(cost)
    prefill = cost["configs"].get("beam50_batch1_prefill")
    full = cost["configs"].get("beam50_batch1")
    if prefill and full:
        share = prefill["per_call"]["p50"] / full["per_call"]["p50"]
        lines += [
            f"- **Where the time goes.** With one new token instead of five, a 50-beam request "
            f"takes {_ms(prefill['per_call']['p50'])} (P50) of its "
            f"{_ms(full['per_call']['p50'])}: {share:.0%} is the first forward pass. Hugging "
            "Face's beam search copies the prompt (76-121 tokens) once per beam before that "
            "pass, so the model encodes the same prompt 50 times. The beams differ only in "
            "what they generate: encoding the prompt once and sharing its attention cache "
            "across the beams would remove most of that work.",
        ]
    if sasrec and full:
        one = next((r for r in sasrec["runs"] if r["batch_size"] == 1 and r["threads"] == 1), None)
        if one:
            ratio = full["per_call"]["p50"] / one["per_call"]["p50"]
            lines.append(
                f"- **Against SASRec.** A 50-beam MiniOneRec request is {ratio:,.0f} times a "
                f"single-threaded SASRec request at the median ({_ms(full['per_call']['p50'])} vs "
                f"{_ms(one['per_call']['p50'])}). Online, the model server runs the same SASRec "
                "encoder in ONNX Runtime and searches FAISS."
            )
    lines.append("")
    return lines


def _swap_sentence(swapped: int | None) -> str:
    if swapped is None:
        return ""
    if swapped == 0:
        return " Nothing was swapped out while it ran (vm_stat's swap-out count)."
    return f" The machine swapped out {_bytes(swapped)} while it ran, so the times include paging."


def _swapped(c: dict) -> int | None:
    if c.get("swapped_out_bytes") is not None:
        return c["swapped_out_bytes"]
    return (c.get("quiet") or {}).get("swapped_out_bytes")


def _busy(c: dict) -> bool:
    q = c.get("quiet")
    return not q["quiet_start"] if q else c["loadavg_start"] > BUSY_LOAD


def _disturbed(c: dict) -> bool:
    return bool((c.get("quiet") or {}).get("disturbed"))


def _quiet_notes(cost: dict) -> list[str]:
    measured = dict(cost["configs"])
    if cost.get("sasrec"):
        measured["SASRec"] = cost["sasrec"]
    notes = []
    for name, c in measured.items():
        attempts = (c.get("quiet") or {}).get("attempts", [])
        if len(attempts) > 1:
            first = ", ".join(attempts[0]["containers_during"])
            notes.append(
                f"- `{name}` was run a second time: other containers ran during the first "
                f"attempt ({first})"
                + (
                    f", and during the second too ({', '.join(attempts[-1]['containers_during'])}"
                    "); it is kept as measured (†)."
                    if _disturbed(c)
                    else "."
                )
            )
        elif _disturbed(c):
            notes.append(
                f"- `{name}`: containers ran during it "
                f"({', '.join(attempts[-1]['containers_during'])}) (†)."
            )
        if attempts and not attempts[-1]["start"]["load1"] < BUSY_LOAD:
            notes.append(
                f"- `{name}` started with a 1-minute load average of "
                f"{attempts[-1]['start']['load1']:.1f} after waiting "
                f"{attempts[-1]['waited_seconds'] / 60:.0f} min for a quiet machine."
            )
    swaps = {name: _swapped(c) for name, c in measured.items()}
    if any(v for v in swaps.values()):
        notes += [
            f"- `{name}`: {_bytes(v)} swapped out while it ran (vm_stat), so its times include "
            "paging."
            for name, v in swaps.items()
            if v
        ]
    elif swaps and all(v == 0 for v in swaps.values()):
        notes.append(
            "- Nothing was swapped out during any measurement (vm_stat's swap-out count did not "
            "change)."
        )
    return [*notes, ""] if notes else []


def _agreement_section(out: dict) -> list[str]:
    if not out.get("agreement"):
        return []
    main = out["main_run"]
    st = out["runs"][main]["summary"]["settings"]
    rows = []
    for a in out["agreement"]:
        s = a["settings"]
        rows.append(
            [
                a["run"],
                f"{s['num_beams']} / {s['batch_size']} / {s['dtype']}",
                a["reference"],
                f"{a['samples']:,}",
                f"{a['identical_top10']:.1%}",
                f"{a['top10_overlap']:.1%}",
                _ci(a["reference_values"]["HR@10"]),
                _ci(a["run_values"]["HR@10"]),
                _signed(a["difference"]["HR@10"]),
            ]
        )
    return [
        "## Other settings on the same samples",
        "",
        f"Each run against the main run ({main}: {st['num_beams']} beams, batch "
        f"{st['batch_size']}, {st['dtype']}), and two runs on the same samples whose settings "
        "differ in one value against each other (the one with the main run's value is the "
        "reference), on the samples both generated for; item rule, paired bootstrap on those "
        "samples' users. Identical top-10 = the same ten SIDs in the same order; overlap = the "
        "share of the reference's top-10 SIDs that the run also has in its top 10.",
        "",
        *_table(
            [
                "Run",
                "Beams / batch / dtype",
                "Against",
                "Samples",
                "Identical top-10",
                "Top-10 overlap",
                "HR@10, reference",
                "HR@10, this run",
                "Difference",
            ],
            rows,
        ),
        "",
    ]


def _runs_section(out: dict) -> list[str]:
    rows = []
    for name, r in out["runs"].items():
        s = r["summary"]
        st = s["settings"]
        rows.append(
            [
                name + (" (main)" if name == out["main_run"] else ""),
                f"{s['samples']:,} / {s['users']:,}",
                f"{st['num_beams']} / {st['batch_size']}",
                st["dtype"],
                s["started"][:16].replace("T", " "),
                _hours(s["wall_seconds"]),
                f"{s['loadavg_start']:.1f}",
                f"{r['comparison']['models'][NAME]['item']['HR@10']['value']:.4f}",
                "match" if r["calc_py"]["ok"] else "**MISMATCH**",
            ]
        )
    return [
        "## Runs",
        "",
        *_table(
            [
                "Run",
                "Samples / users",
                "Beams / batch",
                "dtype",
                "Started",
                "Wall time",
                "Load at start",
                "HR@10 (item)",
                "calc.py check",
            ],
            rows,
        ),
        "",
    ]


