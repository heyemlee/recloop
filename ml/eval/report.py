def _ranking_section(out: dict) -> list[str]:
    r = out["ranking"]
    tun = r["tuning"]
    w_c, w_h = r["weights"]["control"], r["weights"]["sasrec_heavy"]
    sel = tun["trials"][tun["selected"]]
    p = tun["params"]
    imp = tun["importance"]
    total_gain = sum(v["gain"] for v in imp.values()) or 1.0
    trials = sorted(tun["trials"], key=lambda t: -t["cv"][tun["select_by"]])
    lines = [
        "## Ranking: RRF and the LightGBM ranker",
        "",
        "The api orders the home feed by weighted reciprocal rank fusion (RRF) of its three "
        f"recall sources: each returns its top {r['source_k']}, an item scores "
        f"sum over sources of w_s / ({r['rrf_k']} + rank_s), and the first {r['candidates']} "
        "fused items are the candidates (`ml/ranking/candidates.py` replays the api's code on "
        "each split). **RRF** uses the weights of the recall experiment's control variant "
        f"(sasrec {w_c['sasrec']:g}, itemcf {w_c['itemcf']:g}, pop {w_c['pop']:g}), **RRF-heavy** "
        f"those of its sasrec_heavy variant ({w_h['sasrec']:g}, {w_h['itemcf']:g}, "
        f"{w_h['pop']:g}).",
        "",
        "**LambdaRank** re-orders RRF's candidates with LightGBM (`lambdarank`, NDCG@10). The "
        "recall models are fitted on the train rows and the ranker on the validation split: "
        "each validation sample is a query, its candidates the documents, the true next item "
        "the positive. A recall model's scores on its own training data are higher than on new "
        "data, so a ranker trained there would learn to trust them too much. Queries whose "
        "target is not among the candidates carry no pairwise signal and are left out of "
        "training. A missing feature (a source that did not return the item, an unknown price) "
        "stays missing, which LightGBM handles natively.",
        "",
        *_table(
            ["", ""],
            [
                [
                    "Test targets among the candidates",
                    f"{r['test_target_in_candidates']:.1%}: the most any re-ordering of the "
                    "candidates can reach (HR@300)",
                ],
                [
                    "Training queries",
                    f"{tun['train']['queries']:,} of {tun['train']['samples']:,} validation "
                    f"samples have the target among the candidates; {tun['train']['rows']:,} rows",
                ],
                [
                    "Grid",
                    "; ".join(f"{k} in {{{', '.join(map(str, v))}}}" for k, v in tun["grid"].items())
                    + f"; learning rate {p['learning_rate']}, L2 {p['lambda_l2']}, "
                    f"lambdarank truncation level {p['truncation_level']}, early stopping after "
                    f"{p['early_stopping']} rounds without a better NDCG@10",
                ],
                [
                    "Selection",
                    f"{tun['folds']}-fold cross-validation over the validation users (a user's "
                    "samples stay in one fold), by held-out NDCG@10 of every held-out sample "
                    "(item rule, all items ranked, a target outside the candidates is a miss)",
                ],
                [
                    "Selected",
                    f"{p['num_leaves']} leaves, at least {p['min_data_in_leaf']} rows per leaf, "
                    f"feature fraction {p['feature_fraction']}; refitted on all training queries "
                    f"with {tun['rounds']} trees (the mean of its folds' best rounds); CV "
                    f"NDCG@10 {sel['cv']['NDCG@10']:.4f}, HR@10 {sel['cv']['HR@10']:.4f}",
                ],
                [
                    "Runtime",
                    f"LightGBM {tun['lightgbm']} built without OpenMP, one thread, fixed seed; "
                    f"{tun['seconds']:.0f} s for the whole grid and the refit",
                ],
            ],
        ),
        "",
        "Grid, best first (rounds = each fold's best iteration):",
        "",
        *_table(
            ["Leaves", "Min rows per leaf", "Feature fraction", "Rounds", "CV HR@10", "CV NDCG@10"],
            [
                [
                    str(t["params"]["num_leaves"]),
                    str(t["params"]["min_data_in_leaf"]),
                    str(t["params"]["feature_fraction"]),
                    ", ".join(map(str, t["rounds"])),
                    f"{t['cv']['HR@10']:.4f}",
                    f"{t['cv']['NDCG@10']:.4f}",
                ]
                for t in trials
            ],
        ),
        "",
        f"All {len(trials)} configurations lie within "
        f"{trials[0]['cv'][tun['select_by']] - trials[-1]['cv'][tun['select_by']]:.4f} CV NDCG@10 of "
        "each other, far less than the spread between the folds of one configuration (the "
        f"selected one: {min(sel['fold_ndcg10']):.4f} to {max(sel['fold_ndcg10']):.4f}); the grid "
        "hardly matters.",
        "",
        "Features of the selected model (share of the total split gain):",
        "",
        *_table(
            ["Feature", "Definition", "Gain share", "Splits"],
            [
                [f"`{f}`", FEATURE_TEXT.get(f, ""), f"{imp[f]['gain'] / total_gain:.1%}", f"{imp[f]['splits']:,}"]
                for f in sorted(r["features"], key=lambda f: -imp[f]["gain"])
            ],
        ),
        "",
        *_gain_by_segment(out),
        "The item log's click-through rates (design §4.3) are not features: the dataset's "
        "periods have no impressions, and the simulator's clicks follow each user's test targets "
        "(§2.2), so a click-through rate computed from simulated traffic would carry the test "
        "labels into this evaluation.",
        "",
    ]
    return lines


def _gain_by_segment(out: dict) -> list[str]:
    seg = out["segments"]
    pair = "LambdaRank - RRF"
    if pair not in seg["same_day"]["pairs"]:
        return []
    same = seg["same_day"]["pairs"][pair]["NDCG@10"]
    later = seg["later_day"]["pairs"][pair]["NDCG@10"]
    return [
        f"Where the gain over RRF comes from (test, NDCG@10): {_signed(same)} on targets reviewed "
        f"the same day as the last history item, {_signed(later)} on later ones. The gain is "
        "where the next item was mostly reviewed together with the last one; on later targets "
        "the ranker and RRF are level.",
        "",
    ]


def _plain(row: dict, names=METRIC_NAMES) -> list[str]:
    return [f"{row[m]:.4f}" for m in names]


def _variant_label(cfg: dict) -> str:
    loss = (
        "BCE against 1 sampled negative (the upstream loss)"
        if cfg["loss"] == "bce"
        else "full-softmax CE"
    )
    norm = "pre-LN" if cfg["norm_first"] else "post-LN"
    return f"Our SASRec, {loss}, {norm}, {cfg['loss_positions']} positions"


def _paper_section(out: dict) -> list[str]:
    cmp_ = out["sasrec_vs_paper"]
    paper = cmp_["paper"]["rows"]
    ours = cmp_["ours"]
    run = cmp_["minionerec_script"]
    rows = [["Paper, Table 1: SASRec", "as reported"] + _plain(paper["SASRec"])]
    if run is not None:
        label = "MiniOneRec's sasrec.py re-run on this split"
        rows.append([label, "its own code"] + _plain(run["own_metrics"]))
        rows.append([label, "ours"] + [_ci(run["our_metrics"][m]) for m in METRIC_NAMES])
    for var in cmp_["variants"].values():
        rows.append(
            [_variant_label(var["config"]), "ours"] + [_ci(var["test"][m]) for m in METRIC_NAMES]
        )
    sel_cfg = out["sasrec_tuning"]["trials"][out["sasrec_tuning"]["selected"]]["config"]
    rows.append(
        [_variant_label(sel_cfg) + " (selected)", "ours"]
        + [_ci(ours["SASRec"][m]) for m in METRIC_NAMES]
    )
    rows.append(["Paper, Table 1: MiniOneRec", "as reported"] + _plain(paper["MiniOneRec"]))
    rows.append(["Our ItemCF", "ours"] + [_ci(ours["ItemCF"][m]) for m in METRIC_NAMES])

    hr, nd = ours["SASRec"]["HR@10"]["value"], ours["SASRec"]["NDCG@10"]["value"]
    p_hr, p_nd = paper["SASRec"]["HR@10"], paper["SASRec"]["NDCG@10"]
    lines = [
        "## SASRec compared with the paper",
        "",
        f"{cmp_['paper']['source']} reports SASRec on this split. Its baselines were trained "
        f"with {cmp_['paper']['baseline_training']}; MiniOneRec's repository ships that "
        "baseline as `sasrec.py` (1 self-attention block, d = 32, a separate linear output "
        'layer, BCE against one random negative at the last position). "Ours" is our metric '
        'code (item rule, popularity tie order, user-level bootstrap); "its own code" is what '
        "the script prints.",
        "",
        *_table(["Model", "Metrics"] + METRIC_NAMES, rows),
        "",
        f"- **Gap.** Our selected SASRec: HR@10 {hr:.4f}, NDCG@10 {nd:.4f}; the paper: "
        f"{p_hr:.4f} and {p_nd:.4f} ({hr - p_hr:+.4f} = {(hr - p_hr) / p_hr:+.0%}, "
        f"{nd - p_nd:+.4f} = {(nd - p_nd) / p_nd:+.0%}).",
    ]
    if run is not None:
        own_hr = run["own_metrics"]["HR@10"]
        own_nd = run["own_metrics"]["NDCG@10"]
        ci_hr = run["our_metrics"]["HR@10"]["ci"]
        ci_nd = run["our_metrics"]["NDCG@10"]["ci"]
        same = (
            "the same numbers with ours"
            if abs(run["our_metrics"]["HR@10"]["value"] - own_hr) < 5e-5
            and abs(run["our_metrics"]["NDCG@10"]["value"] - own_nd) < 5e-5
            else f"{run['our_metrics']['HR@10']['value']:.4f} HR@10 with ours"
        )
        lines.append(
            f"- **Data and metric.** MiniOneRec's own script, run unmodified with its default "
            f"settings (best validation epoch {run['best_epoch']}), gives HR@10 {own_hr:.4f} and "
            f"NDCG@10 {own_nd:.4f} with its metric code ({same} on the same logits), "
            f"{own_hr - p_hr:+.4f} and {own_nd - p_nd:+.4f} from the paper; this run's 95% "
            f"intervals are [{ci_hr[0]:.4f}, {ci_hr[1]:.4f}] and [{ci_nd[0]:.4f}, {ci_nd[1]:.4f}]. "
            "The paper tuned the learning rate and weight decay and gives no seed. So the split "
            "and the metric reproduce the published baseline to within about one HR@10 point, "
            f"and the gap between it and our SASRec ({hr - own_hr:+.4f} HR@10, "
            f"{nd - own_nd:+.4f} NDCG@10 over this run) is the model and its training."
        )
    else:
        lines.append(
            "- **Data and metric.** MiniOneRec's own script has not been re-run here "
            "(`make paper-sasrec`)."
        )
    variants = cmp_["variants"]
    bce, twin = variants.get("loss=bce"), variants.get("loss=ce twin of loss=bce")
    if bce is not None and twin is not None:
        b_hr, b_nd = bce["test"]["HR@10"]["value"], bce["test"]["NDCG@10"]["value"]
        t_hr, t_nd = twin["test"]["HR@10"]["value"], twin["test"]["NDCG@10"]["value"]
        lines += [
            f"- **Loss.** With the upstream loss our network reaches HR@10 {b_hr:.4f} and "
            f"NDCG@10 {b_nd:.4f} (paper: {p_hr:.4f} and {p_nd:.4f}). Switching only the loss to the full "
            f"softmax (same blocks, LayerNorm and positions) gives {t_hr:.4f} and {t_nd:.4f} "
            f"({t_hr - b_hr:+.4f}, {t_nd - b_nd:+.4f}). With one random negative per "
            "positive almost every negative is easy, so the model learns to tell the target "
            "from random items rather than to rank it above the few items that compete with "
            "it; the softmax compares the target with all 3,459 items at every step, which is "
            "what full-ranking HR / NDCG measure.",
            f"- **Training setup.** The selected configuration (training on the last position "
            f"only, pre-LN) adds {hr - t_hr:+.4f} HR@10 and {nd - t_nd:+.4f} NDCG@10 on top. "
            "Training on every position of a window also fits short, truncated contexts, while "
            "the evaluation always predicts from the full window of up to 10 items.",
        ]
    lines += [
        "- **Other differences.** 2 blocks and d = 64 instead of 1 block and d = 32; item "
        "embeddings shared between input and output (they are the FAISS item vectors); a "
        "padding mask on the keys; early stopping and model selection on validation NDCG@10.",
        "",
    ]
    return lines


def _models_section(out: dict) -> list[str]:
    s, models = out["setup"], out["models"]
    lines = ["## Models", ""]
    for name, r in models.items():
        valid = r["valid"]["item"]
        kind = " (cross-validated)" if r.get("valid_kind") == "cross-validated" else ""
        lines.append(
            f"- **{name}**: {r['description']}. Validation{kind} (item rule): "
            f"HR@10 {valid['HR@10']:.4f}, NDCG@10 {valid['NDCG@10']:.4f}."
        )
    grid = s["itemcf_grid"]
    lines += [
        "",
        f"ItemCF grid ({len(out['itemcf_trials'])} configurations): "
        + "; ".join(f"{k} in {{{', '.join(map(str, vals))}}}" for k, vals in grid.items())
        + ". beta is the popularity penalty on the candidate, gamma the decay over history "
        "positions, lambda the decay over distance inside a training sequence, iuf the "
        "1/log(1 + length) weight per user. Best five on validation:",
        "",
    ]
    top = sorted(out["itemcf_trials"], key=lambda t: -t["valid"][s["select_by"]])[:5]
    lines += _table(
        ["beta", "gamma", "lambda", "iuf", "valid HR@10", "valid NDCG@10"],
        [
            [
                str(t["params"]["beta"]),
                str(t["params"]["history_decay"]),
                str(t["params"]["proximity_decay"]),
                "on" if t["params"]["iuf"] else "off",
                f"{t['valid']['HR@10']:.4f}",
                f"{t['valid']['NDCG@10']:.4f}",
            ]
            for t in top
        ],
    )
    tun = out["sasrec_tuning"]
    base = tun["base"]
    lines += [
        "",
        "SASRec (adapted from pmixer/SASRec.pytorch, Apache-2.0; see `ml/models/sasrec.py`): "
        f"{base['blocks']} self-attention blocks, d = {base['hidden']}, {base['heads']} head, "
        f"history window {base['maxlen']}, item embeddings shared between input and output "
        "(they are the FAISS item vectors). Adam (lr "
        f"{base['lr']}, betas 0.9/0.98), batch {base['batch_size']}, at most "
        f"{base['max_epochs']} epochs, early stopping after {base['patience']} epochs without a "
        "better validation NDCG@10; CPU, fixed seed. Grid: "
        + "; ".join(f"{k} in {{{', '.join(map(str, v))}}}" for k, v in tun["grid"].items())
        + ", plus "
        + ", ".join(f"loss={c['loss']}" for c in tun["extra"])
        + " (the upstream loss, for the comparison above). CE is the full softmax over all "
        "items; BCE scores the positive against one uniformly sampled negative. Positions "
        "'all' trains on the next item at every position of the window, 'last' only at the "
        "final position.",
        "",
    ]
    lines += _table(
        [
            "",
            "dropout",
            "LayerNorm",
            "loss",
            "positions",
            "best epoch",
            "valid HR@10",
            "valid NDCG@10",
        ],
        [
            [
                "selected" if i == tun["selected"] else "",
                str(t["config"]["dropout"]),
                "pre" if t["config"]["norm_first"] else "post",
                t["config"]["loss"].upper(),
                t["config"]["loss_positions"],
                f"{t['best_epoch']} / {t['epochs_run']}",
                f"{t['valid']['HR@10']:.4f}",
                f"{t['valid']['NDCG@10']:.4f}",
            ]
            for i, t in enumerate(tun["trials"])
        ],
    )
    lines.append("")
    return lines
