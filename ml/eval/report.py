def _pass(ok: bool) -> str:
    return "pass" if ok else "**FAIL**"


SEGMENTS = (("same_day", "same day"), ("later_day", "later day"))


def _segment_section(out: dict) -> list[str]:
    seg = out["segments"]
    names = list(out["models"])
    from ml.eval.run import SEGMENT_METRICS

    return [
        "### Targets reviewed on the same day as the last history item",
        "",
        f"Review times are day-granular. In {seg['same_day']['share']:.1%} of the test samples",
        "the target was reviewed on the same day as the last history item; inside a day the",
        "upstream sequence order is the order of the raw review file, not a real time order, so",
        "these next items are mostly items reviewed together. The split is MiniOneRec's and is",
        "kept as is (every method sees the same samples). Every model is reported on both",
        "segments, item rule, with intervals from a user-level bootstrap inside the segment:",
        "",
        *_table(
            ["Model", "Segment", "Samples"] + list(SEGMENT_METRICS),
            [
                [n, label, f"{seg[key]['samples']:,}"]
                + [_ci(seg[key]["models"][n][m]) for m in SEGMENT_METRICS]
                for n in names
                for key, label in SEGMENTS
            ],
        ),
        "",
        "Paired differences by segment:",
        "",
        *_table(
            ["Difference", "Segment", "HR@10", "NDCG@10"],
            [
                [pair, label] + [_signed(seg[key]["pairs"][pair][m]) for m in ("HR@10", "NDCG@10")]
                for pair in seg["same_day"]["pairs"]
                for key, label in SEGMENTS
            ],
        ),
        "",
    ]


