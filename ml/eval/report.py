"""Render docs/results/offline.md from the dict built by ml.eval.run (deterministic output)."""

from __future__ import annotations

from ml.eval import metrics

METRIC_NAMES = [f"HR@{k}" for k in metrics.KS] + [f"NDCG@{k}" for k in metrics.KS]


def _ci(cell: dict, digits: int = 4) -> str:
    lo, hi = cell["ci"]
    return f"{cell['value']:.{digits}f} [{lo:.{digits}f}, {hi:.{digits}f}]"


def _signed(cell: dict, digits: int = 4) -> str:
    lo, hi = cell["ci"]
    return f"{cell['value']:+.{digits}f} [{lo:+.{digits}f}, {hi:+.{digits}f}]"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _results_table(models: dict, rule: str) -> list[str]:
    rows = [[name] + [_ci(r["test"][rule][m]) for m in METRIC_NAMES] for name, r in models.items()]
    return _table(["Model"] + METRIC_NAMES, rows)


def render(out: dict) -> str:
    s, models, v = out["setup"], out["models"], out["verify"]["checks"]
    test_set = v["test_set"]
    lines = [
        "# Offline evaluation",
        "",
        "<!-- Generated by `make eval` (ml/eval/run.py). Do not edit by hand. -->",
        "",
        "Baselines on MiniOneRec's Office Products split (Amazon Review Data 2018). Inputs are",
        "pinned and checksummed by `make data`; see [ADR-0002](../adr/0002-dataset.md).",
        "",
        "## Setup",
        "",
        *_table(
            ["", ""],
            [
                [
                    "Data",
                    "Amazon Review Data (2018) Office Products, MiniOneRec preprocessing "
                    f"(5-core, reviews from {s['window']['final_start']}-01 to "
                    f"{s['window']['final_end']}-01 {s['window']['tz']}, history of up to 10 "
                    "items)",
                ],
                [
                    "Samples",
                    f"train {s['samples']['train']:,} / valid {s['samples']['valid']:,} / "
                    f"test {s['samples']['test']:,}; the test split covers "
                    f"{s['test_users']:,} users",
                ],
                [
                    "Ranking",
                    f"all {s['num_items']:,} items for every sample; items already in the "
                    f"history are not filtered ({test_set['target_in_history']} of "
                    f"{test_set['samples']:,} test targets, "
                    f"{test_set['target_in_history_rate']:.2%}, are repeats)",
                ],
                [
                    "Training data",
                    f"train rows only: {s['train_interactions']:,} interactions of "
                    f"{s['train_users']:,} users (each user's first history item and "
                    "the targets of their train rows)",
                ],
                [
                    "Tuning",
                    f"ItemCF grid on the validation split, selected by {s['select_by']}; "
                    "the test split is scored once",
                ],
                [
                    "Metrics",
                    "HR@K and NDCG@K, K = "
                    + ", ".join(map(str, s["ks"]))
                    + "; NDCG@K = 1/log2(rank + 1) if rank <= K (MiniOneRec's calc.py)",
                ],
                [
                    "Hit rules",
                    "**item** (main): the target item itself; **SID**: any item with the "
                    "target's semantic ID, which is how calc.py scores generated SIDs "
                    f"({v['shared_sids']['groups']} pairs of items share a SID)",
                ],
                ["Ties", "training popularity, then item_id"],
                [
                    "Intervals",
                    f"95%, user-level bootstrap: {s['bootstrap']['B']:,} replicates, "
                    f"seed {s['bootstrap']['seed']}, same replicates for every model",
                ],
            ],
        ),
        "",
        "## Test results",
        "",
        "Item rule (main):",
        "",
        *_results_table(models, "item"),
        "",
        "SID rule:",
        "",
        *_results_table(models, "sid"),
        "",
        "Paired difference ItemCF - Pop (same bootstrap replicates):",
        "",
        *_table(
            ["Rule"] + METRIC_NAMES,
            [
                [rule] + [_signed(out["itemcf_minus_pop"][rule][m]) for m in METRIC_NAMES]
                for rule in ("item", "sid")
            ],
        ),
        "",
    ]
    seg = out["segments"]
    names = list(models)
    lines += [
        "### Targets reviewed on the same day as the last history item",
        "",
        f"Review times are day-granular. In {seg['same_day']['share']:.1%} of the test samples",
        "the target was reviewed on the same day as the last history item; inside a day the",
        "upstream sequence order is the order of the raw review file, not a real time order, so",
        "these next items are mostly items reviewed together. The split is MiniOneRec's and is",
        "kept as is (every method sees the same samples); results by segment, item rule:",
        "",
        *_table(
            ["Segment", "Samples"] + [f"{n} {m}" for n in names for m in ("HR@10", "NDCG@10")],
            [
                [label, f"{seg[key]['samples']:,}"]
                + [_ci(seg[key]["models"][n][m]) for n in names for m in ("HR@10", "NDCG@10")]
                for key, label in (("same_day", "same day"), ("later_day", "later day"))
            ],
        ),
        "",
        "## Models",
        "",
    ]
    for name, r in models.items():
        valid = r["valid"]["item"]
        lines.append(
            f"- **{name}**: {r['description']}. Validation (item rule): "
            f"HR@10 {valid['HR@10']:.4f}, NDCG@10 {valid['NDCG@10']:.4f}."
        )
    grid = s["itemcf_grid"]
    lines += [
        "",
        f"ItemCF grid ({len(out['itemcf_trials'])} configurations): "
        + "; ".join(f"{k} in {{{', '.join(map(str, vals))}}}" for k, vals in grid.items())
        + ". beta is the popularity penalty on the candidate, gamma the decay over history "
        "positions, lambda the decay over distance inside a training sequence, iuf the "
        "1/log(1 + length) weight per user. Best five on validation:",
        "",
    ]
    top = sorted(out["itemcf_trials"], key=lambda t: -t["valid"][s["select_by"]])[:5]
    lines += _table(
        ["beta", "gamma", "lambda", "iuf", "valid HR@10", "valid NDCG@10"],
        [
            [
                str(t["params"]["beta"]),
                str(t["params"]["history_decay"]),
                str(t["params"]["proximity_decay"]),
                "on" if t["params"]["iuf"] else "off",
                f"{t['valid']['HR@10']:.4f}",
                f"{t['valid']['NDCG@10']:.4f}",
            ]
            for t in top
        ],
    )

    sizes = v["sizes"]
    vocab = v["sid_tokens_in_checkpoint_vocab"]
    identical = v["published_files_identical"]
    lines += [
        "",
        "## Data verification (`make data`)",
        "",
        *_table(
            ["Check", "Result"],
            [
                [
                    "Published files rebuilt from the raw UCSD files",
                    _pass(identical["ok"]) + ": train/valid/test CSVs, info file and item.json are "
                    "byte-identical to MiniOneRec's",
                ],
                [
                    "Sizes",
                    _pass(v["sizes"]["ok"]) + f": {sizes['items']:,} items; "
                    f"{sizes['samples']['train']:,} / {sizes['samples']['valid']:,} / "
                    f"{sizes['samples']['test']:,} samples; {sizes['users']:,} users; "
                    f"{sizes['interactions']:,} interactions",
                ],
                [
                    "Timestamps",
                    _pass(v["timestamp_rebuild"]["ok"]) + ": rebuilding the samples "
                    "from the raw reviews reproduces the upstream id order, inter.json and all three "
                    ".inter files, so every interaction carries its review time",
                ],
                [
                    "ASIN <-> item_id",
                    _pass(v["asin_item_id"]["ok"]) + f": one-to-one over "
                    f"{v['asin_item_id']['distinct_asins']:,} items, same ids as index.json and the "
                    "info file",
                ],
                [
                    "Titles and SIDs",
                    _pass(v["titles_and_sids_match_info"]["ok"]) + ": the catalog's "
                    "title and SID of every item equal the info file's",
                ],
                [
                    "SID tokens in the checkpoint vocabulary",
                    _pass(vocab["ok"]) + f": "
                    f"{vocab['distinct_sid_tokens']} tokens ("
                    + ", ".join(f"{k}: {n}" for k, n in vocab["tokens_per_level"].items())
                    + f") all in Office_ckpt's added_tokens.json and tokenizer_config.json; max id "
                    f"{vocab['max_token_id']} < vocab size {vocab['vocab_size']}",
                ],
                [
                    "Shared SIDs",
                    _pass(v["shared_sids"]["ok"]) + f": {v['shared_sids']['groups']} "
                    f"pairs, {v['shared_sids']['distinct_sids']:,} distinct SIDs; "
                    f"{v['shared_sids']['same_title_groups']} of the pairs have identical titles "
                    "(the same product listed twice)",
                ],
            ],
        ),
        "",
        "Items that share a semantic ID:",
        "",
        *_table(
            ["SID", "item_id", "ASIN", "item_id", "ASIN", "Title"],
            [
                [
                    f"`{p['sid']}`",
                    str(p["items"][0]["item_id"]),
                    p["items"][0]["asin"],
                    str(p["items"][1]["item_id"]),
                    p["items"][1]["asin"],
                    p["items"][0]["title"].replace("|", "\\|"),
                ]
                for p in v["shared_sids"]["pairs"]
            ],
        ),
        "",
        "## Cross-check with MiniOneRec's calc.py",
        "",
        "Each model's top-50 per test sample, written as SID strings in MiniOneRec's result",
        "format and scored by `third_party/MiniOneRec/calc.py` (unmodified), against our SID-rule",
        "numbers:",
        "",
    ]
    rows = []
    for c in out["calc_py"]:
        by_k: dict[int, dict] = {}
        for r in c["rows"]:
            by_k.setdefault(r["k"], {})[r["metric"]] = r
        for k, m in by_k.items():
            rows.append(
                [
                    c["model"],
                    str(k),
                    f"{m['HR']['ours']:.8f}",
                    f"{m['HR']['calc_py']:.8f}",
                    f"{m['NDCG']['ours']:.8f}",
                    f"{m['NDCG']['calc_py']:.8f}",
                ]
            )
    lines += _table(["Model", "K", "HR ours", "HR calc.py", "NDCG ours", "NDCG calc.py"], rows)
    lines += [""]
    for c in out["calc_py"]:
        lines.append(
            f"- {c['model']}: {_pass(c['ok'])}, identical to calc.py's printed precision at every"
            f" K (max abs difference {c['max_abs_diff']:.1e}); {c['invalid_predictions']} "
            f"predictions outside the item set; {c['samples']:,} samples."
        )
    lines.append("")
    return "\n".join(lines)


def _pass(ok: bool) -> str:
    return "pass" if ok else "**FAIL**"
