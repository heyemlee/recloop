"""Paths and connection defaults shared by the agent modules (relative to the repo root)."""

from __future__ import annotations

import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

DEFAULT_DATABASE_URL = "postgres://recloop:recloop@localhost:15432/recloop?sslmode=disable"

EVAL_DIR = ROOT / "agent" / "eval"
CASES = EVAL_DIR / "cases.jsonl"  # generated by `make agent-cases`, committed
RUNS = ROOT / "artifacts" / "eval" / "agent"  # one JSON per evaluated agent (not committed)
REPORT = ROOT / "docs" / "results" / "agent.md"  # generated by `make agent-eval`


def database_url() -> str:
    return os.environ.get("DATABASE_URL", DEFAULT_DATABASE_URL)


def interactions_parquet() -> Path:
    """The dataset users' reviews with their split, as `make data` writes them (read-only)."""
    default = ROOT / "data" / "processed" / "interactions.parquet"
    return Path(os.environ.get("RECLOOP_INTERACTIONS", default))


def text_model_dir() -> Path:
    """bge-small-en-v1.5 as downloaded by `make data` (ml.data.download pins and checksums it)."""
    return Path(os.environ.get("RECLOOP_TEXT_MODEL", ROOT / "data" / "hf" / "bge-small-en-v1.5"))
